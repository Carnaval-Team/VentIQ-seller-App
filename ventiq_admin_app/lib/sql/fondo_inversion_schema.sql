-- Recalcula monto_recibido_ref y estado automático de una inversión.
CREATE OR REPLACE FUNCTION public.fn_fdi_recalcular_inversion(p_id_inversion bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_inv      record;
    v_recibido numeric;
    v_nuevo    varchar;
BEGIN
    SELECT * INTO v_inv FROM public.fdi_dat_inversion WHERE id = p_id_inversion FOR UPDATE;
    IF v_inv.id IS NULL THEN
        RETURN;
    END IF;

    SELECT COALESCE(sum(monto_ref), 0) INTO v_recibido
    FROM public.fdi_dat_inversion_recepcion WHERE id_inversion = p_id_inversion;

    v_nuevo := CASE
        WHEN v_recibido <= 0 THEN 'pendiente'
        WHEN v_recibido < v_inv.monto_total_ref THEN 'parcial'
        ELSE 'completado' END;

    IF v_nuevo <> v_inv.estado THEN
        INSERT INTO public.fdi_hist_estado_inversion (
            id_inversion, estado_anterior, estado_nuevo, origen, motivo, created_by
        ) VALUES (
            p_id_inversion, v_inv.estado, v_nuevo, 'automatico',
            'Recalculo por recepciones', auth.uid());
    END IF;

    UPDATE public.fdi_dat_inversion
    SET monto_recibido_ref = v_recibido,
        estado             = v_nuevo,
        estado_manual      = false,
        -- Si llega a cubrir el total, la marca de revisión se quita sola.
        requiere_revision  = CASE WHEN v_recibido >= v_inv.monto_total_ref
                                  THEN false ELSE requiere_revision END,
        motivo_revision    = CASE WHEN v_recibido >= v_inv.monto_total_ref
                                  THEN NULL ELSE motivo_revision END,
        monto_faltante_ref = CASE WHEN v_recibido >= v_inv.monto_total_ref
                                  THEN NULL ELSE monto_faltante_ref END,
        updated_at         = now()
    WHERE id = p_id_inversion;
END;
$$;

-- p_fuentes: jsonb [{id_cuenta, id_medio_pago, moneda, monto, tasa_a_ref}]
CREATE OR REPLACE FUNCTION public.fn_fdi_crear_inversion(
    p_id_tienda        bigint,
    p_identificador    varchar,
    p_detalles         text,
    p_descripcion      text,
    p_moneda_referencia text,
    p_fuentes          jsonb,
    p_idempotency_key  uuid DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_existente   bigint;
    v_id          bigint;
    v_fuente      jsonb;
    v_id_cuenta   bigint;
    v_id_medio    smallint;
    v_moneda      text;
    v_monto       numeric;
    v_tasa        numeric;
    v_monto_ref   numeric;
    v_total_ref   numeric := 0;
BEGIN
    IF NOT public.fn_user_is_gerente_or_superadmin(p_id_tienda) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF p_identificador IS NULL OR btrim(p_identificador) = '' THEN
        RAISE EXCEPTION 'El identificador de la inversión es obligatorio' USING ERRCODE = 'P0002';
    END IF;
    IF p_fuentes IS NULL OR jsonb_array_length(p_fuentes) = 0 THEN
        RAISE EXCEPTION 'Debe indicar al menos una fuente' USING ERRCODE = 'P0002';
    END IF;

    IF p_idempotency_key IS NOT NULL THEN
        SELECT id INTO v_existente
        FROM public.fdi_dat_inversion WHERE idempotency_key = p_idempotency_key;
        IF v_existente IS NOT NULL THEN
            RETURN jsonb_build_object('status', 'ok', 'id_inversion', v_existente, 'duplicada', true);
        END IF;
    END IF;

    INSERT INTO public.fdi_dat_inversion (
        id_tienda, idempotency_key, identificador, detalles, descripcion,
        moneda_referencia, estado, created_by
    ) VALUES (
        p_id_tienda, p_idempotency_key, btrim(p_identificador), p_detalles,
        p_descripcion, p_moneda_referencia, 'pendiente', auth.uid()
    ) RETURNING id INTO v_id;

    FOR v_fuente IN SELECT * FROM jsonb_array_elements(p_fuentes)
    LOOP
        v_id_cuenta := (v_fuente->>'id_cuenta')::bigint;
        v_id_medio  := (v_fuente->>'id_medio_pago')::smallint;
        v_moneda    := COALESCE(NULLIF(TRIM(v_fuente->>'moneda'), ''), 'CUP');
        v_monto     := (v_fuente->>'monto')::numeric;
        v_tasa      := COALESCE((v_fuente->>'tasa_a_ref')::numeric, 1);
        IF v_moneda = p_moneda_referencia THEN
            v_tasa := 1;
        END IF;

        IF v_monto IS NULL OR v_monto <= 0 OR v_tasa <= 0 THEN
            RAISE EXCEPTION 'Fuente inválida: monto y tasa deben ser > 0' USING ERRCODE = 'P0002';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM public.fdi_dat_cuenta
                       WHERE id = v_id_cuenta AND id_tienda = p_id_tienda) THEN
            RAISE EXCEPTION 'Cuenta % no pertenece a la tienda', v_id_cuenta
                USING ERRCODE = 'P0002';
        END IF;

        v_monto_ref := v_monto * v_tasa;
        v_total_ref := v_total_ref + v_monto_ref;

        -- Descuenta la fuente del fondo.
        PERFORM public._fdi_aplicar_movimiento(
            p_id_tienda, v_id_cuenta, v_id_medio, v_moneda, -v_monto,
            'extraccion_inversion',
            p_id_inversion := v_id,
            p_observacion := 'Extracción para inversión ' || p_identificador);

        INSERT INTO public.fdi_dat_inversion_fuente (
            id_inversion, id_cuenta, id_medio_pago, moneda, monto, tasa_a_ref, monto_ref
        ) VALUES (v_id, v_id_cuenta, v_id_medio, v_moneda, v_monto, v_tasa, v_monto_ref);
    END LOOP;

    UPDATE public.fdi_dat_inversion
    SET monto_total_ref = v_total_ref, updated_at = now()
    WHERE id = v_id;

    INSERT INTO public.fdi_hist_estado_inversion (
        id_inversion, estado_anterior, estado_nuevo, origen, motivo, created_by
    ) VALUES (v_id, NULL, 'pendiente', 'automatico', 'Creación de inversión', auth.uid());

    RETURN jsonb_build_object(
        'status', 'ok', 'id_inversion', v_id, 'monto_total_ref', v_total_ref);
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_cambiar_estado_inversion(
    p_id_inversion bigint,
    p_estado       varchar,
    p_motivo       text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_inv record;
BEGIN
    SELECT * INTO v_inv FROM public.fdi_dat_inversion WHERE id = p_id_inversion FOR UPDATE;
    IF v_inv.id IS NULL THEN
        RAISE EXCEPTION 'Inversión % no encontrada', p_id_inversion USING ERRCODE = 'P0002';
    END IF;
    IF NOT public.fn_user_is_gerente_or_superadmin(v_inv.id_tienda) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF p_estado NOT IN ('pendiente', 'parcial', 'completado') THEN
        RAISE EXCEPTION 'Estado inválido: %', p_estado USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO public.fdi_hist_estado_inversion (
        id_inversion, estado_anterior, estado_nuevo, origen, motivo, created_by
    ) VALUES (p_id_inversion, v_inv.estado, p_estado, 'manual', p_motivo, auth.uid());

    UPDATE public.fdi_dat_inversion
    SET estado            = p_estado,
        estado_manual     = true,
        -- Completado a mano con faltante → marca de revisión.
        requiere_revision = CASE
            WHEN p_estado = 'completado' AND monto_recibido_ref < monto_total_ref
            THEN true ELSE requiere_revision END,
        motivo_revision   = CASE
            WHEN p_estado = 'completado' AND monto_recibido_ref < monto_total_ref
            THEN 'completado_con_faltante' ELSE motivo_revision END,
        monto_faltante_ref = CASE
            WHEN p_estado = 'completado' AND monto_recibido_ref < monto_total_ref
            THEN monto_total_ref - monto_recibido_ref ELSE monto_faltante_ref END,
        updated_at = now()
    WHERE id = p_id_inversion;

    RETURN jsonb_build_object('status', 'ok');
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_vincular_recepcion(
    p_id_operacion     bigint,
    p_id_inversion     bigint,
    p_monto            numeric,
    p_moneda           text,
    p_tasa_a_ref       numeric DEFAULT 1,
    p_confirmar_exceso boolean DEFAULT false
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_inv      record;
    v_op_tienda bigint;
    v_monto_ref numeric;
BEGIN
    SELECT * INTO v_inv FROM public.fdi_dat_inversion WHERE id = p_id_inversion;
    IF v_inv.id IS NULL THEN
        RAISE EXCEPTION 'Inversión % no encontrada', p_id_inversion USING ERRCODE = 'P0002';
    END IF;

    SELECT id_tienda INTO v_op_tienda FROM public.app_dat_operaciones WHERE id = p_id_operacion;
    IF v_op_tienda IS NULL OR v_op_tienda <> v_inv.id_tienda THEN
        RAISE EXCEPTION 'La recepción % no pertenece a la tienda de la inversión',
            p_id_operacion USING ERRCODE = 'P0002';
    END IF;
    IF p_monto IS NULL OR p_monto <= 0 THEN
        RAISE EXCEPTION 'El monto de la recepción debe ser > 0' USING ERRCODE = 'P0002';
    END IF;

    IF p_moneda = v_inv.moneda_referencia THEN
        p_tasa_a_ref := 1;
    END IF;
    IF p_tasa_a_ref IS NULL OR p_tasa_a_ref <= 0 THEN
        RAISE EXCEPTION 'La tasa a la moneda de referencia debe ser > 0' USING ERRCODE = 'P0002';
    END IF;
    v_monto_ref := p_monto * p_tasa_a_ref;

    IF v_inv.monto_recibido_ref + v_monto_ref > v_inv.monto_total_ref
       AND NOT p_confirmar_exceso THEN
        RETURN jsonb_build_object(
            'status', 'requires_confirmation',
            'code', 'exceso_recepcion',
            'monto_total_ref', v_inv.monto_total_ref,
            'monto_recibido_ref', v_inv.monto_recibido_ref,
            'monto_nuevo_ref', v_monto_ref);
    END IF;

    INSERT INTO public.fdi_dat_inversion_recepcion (
        id_inversion, id_operacion, monto_recepcion, moneda_recepcion,
        tasa_a_ref, monto_ref, confirmada_con_exceso, created_by
    ) VALUES (
        p_id_inversion, p_id_operacion, p_monto, p_moneda,
        p_tasa_a_ref, v_monto_ref,
        v_inv.monto_recibido_ref + v_monto_ref > v_inv.monto_total_ref,
        auth.uid()
    );

    PERFORM public.fn_fdi_recalcular_inversion(p_id_inversion);

    RETURN jsonb_build_object('status', 'ok', 'monto_ref', v_monto_ref);
END;
$$;

-- Llamada al cancelar una recepción: quita el vínculo y recalcula.
CREATE OR REPLACE FUNCTION public.fn_fdi_desvincular_recepcion(p_id_operacion bigint)
