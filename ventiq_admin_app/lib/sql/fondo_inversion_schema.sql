-- Aplica un delta al saldo (cuenta+medio+moneda) y registra el movimiento.
-- Crea la fila de saldo si no existe; bloquea FOR UPDATE; falla si queda < 0.
CREATE OR REPLACE FUNCTION public._fdi_aplicar_movimiento(
    p_id_tienda        bigint,
    p_id_cuenta        bigint,
    p_id_medio_pago    smallint,
    p_moneda           text,
    p_delta            numeric,
    p_tipo             varchar,
    p_id_liquidacion   bigint DEFAULT NULL,
    p_id_transferencia bigint DEFAULT NULL,
    p_id_inversion     bigint DEFAULT NULL,
    p_observacion      text   DEFAULT NULL
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_saldo_id     bigint;
    v_saldo_previo numeric;
    v_saldo_nuevo  numeric;
BEGIN
    SELECT id, saldo INTO v_saldo_id, v_saldo_previo
    FROM public.fdi_dat_saldo
    WHERE id_cuenta = p_id_cuenta
      AND id_medio_pago = p_id_medio_pago
      AND moneda = p_moneda
    FOR UPDATE;

    IF v_saldo_id IS NULL THEN
        INSERT INTO public.fdi_dat_saldo
            (id_tienda, id_cuenta, id_medio_pago, moneda, saldo)
        VALUES (p_id_tienda, p_id_cuenta, p_id_medio_pago, p_moneda, 0)
        RETURNING id, saldo INTO v_saldo_id, v_saldo_previo;
    END IF;

    v_saldo_nuevo := v_saldo_previo + p_delta;
    IF v_saldo_nuevo < 0 THEN
        RAISE EXCEPTION 'Saldo insuficiente en cuenta %, medio %, moneda %: disponible %, requerido %',
            p_id_cuenta, p_id_medio_pago, p_moneda, v_saldo_previo, -p_delta
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public.fdi_dat_saldo
    SET saldo = v_saldo_nuevo, updated_at = now()
    WHERE id = v_saldo_id;

    INSERT INTO public.fdi_dat_movimiento (
        id_tienda, id_cuenta, id_medio_pago, moneda, monto,
        saldo_anterior, saldo_nuevo, tipo,
        id_liquidacion, id_transferencia, id_inversion,
        observacion, created_by
    ) VALUES (
        p_id_tienda, p_id_cuenta, p_id_medio_pago, p_moneda, p_delta,
        v_saldo_previo, v_saldo_nuevo, p_tipo,
        p_id_liquidacion, p_id_transferencia, p_id_inversion,
        p_observacion, auth.uid()
    );
END;
$$;

-- Órdenes de venta elegibles para liquidar: tipo 'venta', es_pagada, estado
-- actual = 2 (completada), dentro del periodo según el modo de filtro
-- ('creacion' | 'completado' | 'turnos_abiertos'), excluyendo las ya
-- liquidadas (presentes en fdi_dat_liquidacion_orden).
CREATE OR REPLACE FUNCTION public._fdi_ops_elegibles(
    p_id_tienda bigint,
    p_desde     date,
    p_hasta     date,
    p_modo      text DEFAULT 'creacion'
) RETURNS TABLE(id bigint, ts_op timestamptz)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_id_tipo_venta bigint;
    v_modo          text := lower(coalesce(nullif(trim(p_modo), ''), 'creacion'));
BEGIN
    SELECT t.id INTO v_id_tipo_venta
    FROM public.app_nom_tipo_operacion t
    WHERE lower(t.denominacion) = 'venta'
    LIMIT 1;

    IF v_id_tipo_venta IS NULL THEN
        RETURN;
    END IF;

    IF v_modo = 'turnos_abiertos' THEN
        -- Mismo criterio que fn_reporte_ventas_con_proveedor_por_turno_v2:
        -- turnos con apertura en el rango; la operación cae entre apertura
        -- y cierre del turno por id de operación.
        RETURN QUERY
        WITH turnos AS (
            SELECT ct.id_tpv, ct.id_operacion_apertura, ct.id_operacion_cierre,
                   v.uuid
            FROM public.app_dat_caja_turno ct
            JOIN public.app_dat_vendedor v ON v.id = ct.id_vendedor
            JOIN public.app_dat_tpv tp ON tp.id = ct.id_tpv
            WHERE tp.id_tienda = p_id_tienda
              AND ct.fecha_apertura::date >= COALESCE(p_desde, CURRENT_DATE)
              AND ct.fecha_apertura::date <= COALESCE(p_hasta, CURRENT_DATE)
        )
        SELECT DISTINCT o.id, o.created_at
        FROM public.app_dat_operaciones o
        JOIN public.app_dat_operacion_venta ov
          ON ov.id_operacion = o.id AND ov.es_pagada = true
        JOIN turnos t
          ON t.uuid = o.uuid
         AND ov.id_tpv = t.id_tpv
         AND o.id >= t.id_operacion_apertura
         AND o.id <= COALESCE(t.id_operacion_cierre,
                              (SELECT max(o2.id) FROM public.app_dat_operaciones o2))
        CROSS JOIN LATERAL (
            SELECT eo.estado
            FROM public.app_dat_estado_operacion eo
            WHERE eo.id_operacion = o.id
            ORDER BY eo.id DESC LIMIT 1
        ) e
        WHERE o.id_tienda = p_id_tienda
          AND o.id_tipo_operacion = v_id_tipo_venta
          AND e.estado = 2
          AND NOT EXISTS (
              SELECT 1 FROM public.fdi_dat_liquidacion_orden lo
              WHERE lo.id_operacion_venta = o.id);
    ELSE
        RETURN QUERY
        SELECT o.id,
               CASE WHEN v_modo = 'completado' THEN e.ts_estado ELSE o.created_at END
        FROM public.app_dat_operaciones o
        JOIN public.app_dat_operacion_venta ov
          ON ov.id_operacion = o.id AND ov.es_pagada = true
        CROSS JOIN LATERAL (
            SELECT eo.estado, eo.created_at AS ts_estado
            FROM public.app_dat_estado_operacion eo
            WHERE eo.id_operacion = o.id
            ORDER BY eo.id DESC LIMIT 1
        ) e
        WHERE o.id_tienda = p_id_tienda
          AND o.id_tipo_operacion = v_id_tipo_venta
          AND e.estado = 2
          AND (p_desde IS NULL OR
               CASE WHEN v_modo = 'completado' THEN e.ts_estado ELSE o.created_at END::date >= p_desde)
          AND (p_hasta IS NULL OR
               CASE WHEN v_modo = 'completado' THEN e.ts_estado ELSE o.created_at END::date <= p_hasta)
          AND NOT EXISTS (
              SELECT 1 FROM public.fdi_dat_liquidacion_orden lo
              WHERE lo.id_operacion_venta = o.id);
    END IF;
END;
$$;

