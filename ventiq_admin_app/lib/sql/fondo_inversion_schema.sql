CREATE OR REPLACE FUNCTION public.fn_fdi_ventas_por_medio_moneda(
    p_id_tienda bigint,
    p_desde     date DEFAULT NULL,
    p_hasta     date DEFAULT NULL,
    p_modo      text DEFAULT 'creacion'
) RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_result      jsonb;
    v_tasa_fallback numeric;
BEGIN
    IF NOT public.fn_user_can_access_tienda(p_id_tienda) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', p_id_tienda USING ERRCODE = '42501';
    END IF;

    SELECT tc.tasa INTO v_tasa_fallback
    FROM public.tasas_conversion tc
    WHERE tc.moneda_origen = 'USD' AND tc.moneda_destino = 'CUP'
    ORDER BY tc.fecha_actualizacion DESC
    LIMIT 1;

    WITH elig AS MATERIALIZED (
        SELECT * FROM public._fdi_ops_elegibles(p_id_tienda, p_desde, p_hasta, p_modo)
    ),
    -- Órdenes de venta del periodo ya liquidadas (solo para el contador).
    excluidas AS (
        SELECT o.id
        FROM public.app_dat_operaciones o
        JOIN public.fdi_dat_liquidacion_orden lo ON lo.id_operacion_venta = o.id
        WHERE o.id_tienda = p_id_tienda
          AND (p_desde IS NULL OR o.created_at::date >= p_desde)
          AND (p_hasta IS NULL OR o.created_at::date <= p_hasta)
    ),
    pagos AS (
        SELECT pv.id_medio_pago,
               COALESCE(NULLIF(TRIM(pv.moneda), ''), 'CUP') AS moneda,
               pv.monto,
               COALESCE(pv.monto_cup_equivalente, pv.monto) AS monto_cup
        FROM elig e
        JOIN public.app_dat_pago_venta pv ON pv.id_operacion_venta = e.id
    ),
    medios AS (
        SELECT p.id_medio_pago, mp.denominacion AS medio_pago, p.moneda,
               SUM(p.monto)     AS monto_vendido,
               SUM(p.monto_cup) AS monto_vendido_cup
        FROM pagos p
        LEFT JOIN public.app_nom_medio_pago mp ON mp.id = p.id_medio_pago
        GROUP BY p.id_medio_pago, mp.denominacion, p.moneda
    ),
    -- Costo CUP por línea de venta: costo histórico de la presentación en el
    -- momento de la operación, fallback precio_promedio de la presentación,
    -- fallback última recepción; multiplicado por la tasa histórica.
    lineas AS (
        SELECT ep.id_producto, ep.id_presentacion, ep.cantidad, e.ts_op
        FROM elig e
        JOIN public.app_dat_extraccion_productos ep ON ep.id_operacion = e.id
        WHERE ep.cantidad > 0
    ),
    costo AS (
        SELECT SUM(l.cantidad * COALESCE(c.costo_usd, 0)
                   * COALESCE(t.tasa, v_tasa_fallback, 1)) AS costo_cup
        FROM lineas l
        CROSS JOIN LATERAL (
            SELECT COALESCE(
                (SELECT pc.precio_costo_usd
                 FROM public.app_dat_precio_costo pc
                 WHERE pc.id_presentacion = l.id_presentacion
                   AND pc.created_at <= l.ts_op
                 ORDER BY pc.created_at DESC LIMIT 1),
                (SELECT pp.precio_promedio
                 FROM public.app_dat_producto_presentacion pp
                 WHERE pp.id = l.id_presentacion),
                (SELECT pb.precio_promedio
                 FROM public.app_dat_producto_presentacion pb
                 WHERE pb.id_producto = l.id_producto AND pb.es_base = true
                 ORDER BY pb.id LIMIT 1),
                0) AS costo_usd
        ) c
        CROSS JOIN LATERAL (
            SELECT tc.valor_cambio AS tasa
            FROM public.tasa_cambio_extraoficial tc
            WHERE tc.id_tienda = p_id_tienda AND tc.activo = true
              AND tc.created_at::date <= l.ts_op::date
            ORDER BY tc.created_at DESC LIMIT 1
        ) t
    )
    SELECT jsonb_build_object(
        'modo',               lower(coalesce(nullif(trim(p_modo), ''), 'creacion')),
        'fecha_desde',        p_desde,
        'fecha_hasta',        p_hasta,
        'ordenes_elegibles',  (SELECT count(*) FROM elig),
        'ordenes_excluidas',  (SELECT count(*) FROM excluidas),
        'venta_total_cup',    COALESCE((SELECT sum(monto_vendido_cup) FROM medios), 0),
        'costo_total_cup',    COALESCE((SELECT costo_cup FROM costo), 0),
        'ganancia_cup',       COALESCE((SELECT sum(monto_vendido_cup) FROM medios), 0)
                              - COALESCE((SELECT costo_cup FROM costo), 0),
        'medios',             COALESCE((SELECT jsonb_agg(to_jsonb(m) ORDER BY m.medio_pago, m.moneda)
                                        FROM medios m), '[]'::jsonb)
    ) INTO v_result;

    RETURN v_result;
END;
$$;

