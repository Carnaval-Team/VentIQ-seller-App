CREATE OR REPLACE FUNCTION public.fn_fdi_transferir(
    p_id_tienda            bigint,
    p_id_cuenta_origen     bigint,
    p_id_medio_pago_origen smallint,
    p_moneda_origen        text,
    p_id_cuenta_destino    bigint,
    p_id_medio_pago_destino smallint,
    p_moneda_destino       text,
    p_monto_destino        numeric,
    p_tasa                 numeric DEFAULT 1,
    p_porcentaje_costo     numeric DEFAULT 0,
    p_id_transferencia_corregida bigint DEFAULT NULL,
    p_observacion          text   DEFAULT NULL,
    p_idempotency_key      uuid   DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_existente   bigint;
    v_id          bigint;
    v_base_origen numeric;
    v_comision    numeric;
    v_total_origen numeric;
BEGIN
    IF NOT public.fn_user_is_gerente_or_superadmin(p_id_tienda) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin puede transferir' USING ERRCODE = '42501';
    END IF;
    IF p_monto_destino IS NULL OR p_monto_destino <= 0 THEN
        RAISE EXCEPTION 'El monto debe ser mayor que 0' USING ERRCODE = 'P0002';
    END IF;
    IF p_tasa IS NULL OR p_tasa <= 0 THEN
        RAISE EXCEPTION 'La tasa debe ser mayor que 0' USING ERRCODE = 'P0002';
    END IF;
    IF p_id_transferencia_corregida IS NOT NULL AND COALESCE(p_porcentaje_costo, 0) <> 0 THEN
        RAISE EXCEPTION 'Las transferencias de corrección deben ser al 0%% de costo'
            USING ERRCODE = 'P0002';
    END IF;
    IF (p_id_cuenta_origen = p_id_cuenta_destino)
       AND (p_id_medio_pago_origen = p_id_medio_pago_destino)
       AND (p_moneda_origen = p_moneda_destino) THEN
        RAISE EXCEPTION 'Origen y destino no pueden ser iguales' USING ERRCODE = 'P0002';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.fdi_dat_cuenta
                   WHERE id = p_id_cuenta_origen AND id_tienda = p_id_tienda)
       OR NOT EXISTS (SELECT 1 FROM public.fdi_dat_cuenta
                      WHERE id = p_id_cuenta_destino AND id_tienda = p_id_tienda) THEN
        RAISE EXCEPTION 'Cuenta origen o destino no pertenece a la tienda'
            USING ERRCODE = 'P0002';
    END IF;

    IF p_idempotency_key IS NOT NULL THEN
        SELECT id INTO v_existente
        FROM public.fdi_dat_transferencia WHERE idempotency_key = p_idempotency_key;
        IF v_existente IS NOT NULL THEN
            RETURN jsonb_build_object('status', 'ok', 'id_transferencia', v_existente, 'duplicada', true);
        END IF;
    END IF;

    -- La tasa convierte monto destino → moneda origen.
    v_base_origen  := p_monto_destino * p_tasa;
    v_comision     := round(v_base_origen * COALESCE(p_porcentaje_costo, 0) / 100, 2);
    v_total_origen := v_base_origen + v_comision;

    INSERT INTO public.fdi_dat_transferencia (
        id_tienda, idempotency_key,
        id_cuenta_origen, id_medio_pago_origen, moneda_origen,
        id_cuenta_destino, id_medio_pago_destino, moneda_destino,
        monto_destino, tasa, monto_base_origen,
        porcentaje_costo, monto_comision, monto_total_origen,
        id_transferencia_corregida, observacion, created_by
    ) VALUES (
        p_id_tienda, p_idempotency_key,
        p_id_cuenta_origen, p_id_medio_pago_origen, p_moneda_origen,
        p_id_cuenta_destino, p_id_medio_pago_destino, p_moneda_destino,
        p_monto_destino, p_tasa, v_base_origen,
        COALESCE(p_porcentaje_costo, 0), v_comision, v_total_origen,
        p_id_transferencia_corregida, p_observacion, auth.uid()
    ) RETURNING id INTO v_id;

    PERFORM public._fdi_aplicar_movimiento(
        p_id_tienda, p_id_cuenta_origen, p_id_medio_pago_origen, p_moneda_origen,
        -v_base_origen, 'transferencia_salida',
        p_id_transferencia := v_id, p_observacion := p_observacion);

    IF v_comision > 0 THEN
        PERFORM public._fdi_aplicar_movimiento(
            p_id_tienda, p_id_cuenta_origen, p_id_medio_pago_origen, p_moneda_origen,
            -v_comision, 'comision_transferencia',
            p_id_transferencia := v_id,
            p_observacion := 'Comisión ' || p_porcentaje_costo || '% transferencia #' || v_id);
    END IF;

    PERFORM public._fdi_aplicar_movimiento(
        p_id_tienda, p_id_cuenta_destino, p_id_medio_pago_destino, p_moneda_destino,
        p_monto_destino, 'transferencia_entrada',
        p_id_transferencia := v_id, p_observacion := p_observacion);

    RETURN jsonb_build_object(
        'status', 'ok', 'id_transferencia', v_id,
        'monto_base_origen', v_base_origen,
        'monto_comision', v_comision,
        'monto_total_origen', v_total_origen);
END;
$$;

