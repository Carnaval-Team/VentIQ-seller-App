-- Ajuste de corrección negativo ligado a una liquidación: descuenta de la
-- cuenta destino de esa liquidación, hasta lo que la liquidación ingresó en
-- ese medio/moneda menos correcciones previas.
CREATE OR REPLACE FUNCTION public.fn_fdi_ajuste_correccion_liquidacion(
    p_id_tienda       bigint,
    p_id_liquidacion  bigint,
    p_id_medio_pago   smallint,
    p_moneda          text,
    p_monto           numeric,
    p_motivo          text,
    p_idempotency_key uuid DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_liq       record;
    v_ingresado numeric;
    v_corregido numeric;
BEGIN
    IF NOT public.fn_user_is_gerente_or_superadmin(p_id_tienda) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF p_monto IS NULL OR p_monto <= 0 THEN
        RAISE EXCEPTION 'El monto debe ser mayor que 0' USING ERRCODE = 'P0002';
    END IF;
    IF p_motivo IS NULL OR btrim(p_motivo) = '' THEN
        RAISE EXCEPTION 'El motivo de la corrección es obligatorio' USING ERRCODE = 'P0002';
    END IF;

    SELECT * INTO v_liq FROM public.fdi_dat_liquidacion
    WHERE id = p_id_liquidacion AND id_tienda = p_id_tienda;
    IF v_liq.id IS NULL THEN
        RAISE EXCEPTION 'Liquidación % no encontrada en la tienda', p_id_liquidacion
            USING ERRCODE = 'P0002';
    END IF;

    SELECT COALESCE(sum(monto_inversion), 0) INTO v_ingresado
    FROM public.fdi_dat_liquidacion_detalle
    WHERE id_liquidacion = p_id_liquidacion
      AND id_medio_pago = p_id_medio_pago AND moneda = p_moneda;

    SELECT COALESCE(sum(-m.monto), 0) INTO v_corregido
    FROM public.fdi_dat_movimiento m
    WHERE m.id_liquidacion = p_id_liquidacion AND m.tipo = 'ajuste_correccion'
      AND m.id_medio_pago = p_id_medio_pago AND m.moneda = p_moneda;

    IF p_monto > v_ingresado - v_corregido THEN
        RAISE EXCEPTION 'La corrección (%) supera lo corregible de la liquidación (% menos % previas)',
            p_monto, v_ingresado, v_corregido USING ERRCODE = 'P0002';
    END IF;
    IF p_idempotency_key IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.fdi_dat_movimiento
        WHERE id_liquidacion = p_id_liquidacion AND tipo = 'ajuste_correccion'
          AND observacion LIKE '%idem:' || p_idempotency_key::text) THEN
        RETURN jsonb_build_object('status', 'ok', 'duplicada', true);
    END IF;

    PERFORM public._fdi_aplicar_movimiento(
        p_id_tienda, v_liq.id_cuenta_destino, p_id_medio_pago, p_moneda,
        -p_monto, 'ajuste_correccion',
        p_id_liquidacion := p_id_liquidacion,
        p_observacion := p_motivo
            || CASE WHEN p_idempotency_key IS NOT NULL
                    THEN ' · idem:' || p_idempotency_key::text ELSE '' END);

    RETURN jsonb_build_object('status', 'ok');
END;
$$;

