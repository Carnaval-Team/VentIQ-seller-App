-- Saldos por concepto → cuenta → medio → moneda, más totales por moneda.
CREATE OR REPLACE FUNCTION public.fn_fdi_saldos(p_id_tienda bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NOT public.fn_user_can_access_tienda(p_id_tienda) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', p_id_tienda USING ERRCODE = '42501';
    END IF;

    RETURN (
        WITH saldos AS (
            SELECT s.id_cuenta, s.id_medio_pago, s.moneda, s.saldo,
                   c.id_concepto, c.nombre AS cuenta,
                   co.denominacion AS concepto,
                   mp.denominacion AS medio_pago
            FROM public.fdi_dat_saldo s
            JOIN public.fdi_dat_cuenta c   ON c.id = s.id_cuenta
            JOIN public.fdi_dat_concepto co ON co.id = c.id_concepto
            LEFT JOIN public.app_nom_medio_pago mp ON mp.id = s.id_medio_pago
            WHERE s.id_tienda = p_id_tienda
        )
        SELECT jsonb_build_object(
            'saldos', COALESCE((SELECT jsonb_agg(to_jsonb(s) ORDER BY s.concepto, s.cuenta, s.medio_pago, s.moneda) FROM saldos s), '[]'::jsonb),
            'totales_por_moneda', COALESCE((
                SELECT jsonb_object_agg(moneda, total)
                FROM (SELECT moneda, sum(saldo) AS total FROM saldos GROUP BY moneda) t), '{}'::jsonb)
        )
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_movimientos(
    p_id_tienda   bigint,
    p_desde       date DEFAULT NULL,
    p_hasta       date DEFAULT NULL,
    p_id_concepto bigint DEFAULT NULL,
    p_id_cuenta   bigint DEFAULT NULL,
    p_id_medio_pago smallint DEFAULT NULL,
    p_moneda      text DEFAULT NULL,
    p_tipo        varchar DEFAULT NULL,
    p_limite      integer DEFAULT 500
) RETURNS TABLE (
    id bigint, id_cuenta bigint, cuenta varchar, concepto varchar,
    id_medio_pago smallint, medio_pago varchar, moneda text,
    monto numeric, saldo_anterior numeric, saldo_nuevo numeric,
    tipo varchar, id_liquidacion bigint, id_transferencia bigint,
    id_inversion bigint, observacion text, created_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NOT public.fn_user_can_access_tienda(p_id_tienda) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', p_id_tienda USING ERRCODE = '42501';
    END IF;

    RETURN QUERY
    SELECT m.id, m.id_cuenta, c.nombre, co.denominacion,
           m.id_medio_pago, mp.denominacion, m.moneda,
           m.monto, m.saldo_anterior, m.saldo_nuevo,
           m.tipo, m.id_liquidacion, m.id_transferencia,
           m.id_inversion, m.observacion, m.created_at
    FROM public.fdi_dat_movimiento m
    JOIN public.fdi_dat_cuenta c   ON c.id = m.id_cuenta
    JOIN public.fdi_dat_concepto co ON co.id = c.id_concepto
    LEFT JOIN public.app_nom_medio_pago mp ON mp.id = m.id_medio_pago
    WHERE m.id_tienda = p_id_tienda
      AND (p_desde IS NULL OR m.created_at::date >= p_desde)
      AND (p_hasta IS NULL OR m.created_at::date <= p_hasta)
      AND (p_id_concepto IS NULL OR c.id_concepto = p_id_concepto)
      AND (p_id_cuenta IS NULL OR m.id_cuenta = p_id_cuenta)
      AND (p_id_medio_pago IS NULL OR m.id_medio_pago = p_id_medio_pago)
      AND (p_moneda IS NULL OR m.moneda = p_moneda)
      AND (p_tipo IS NULL OR m.tipo = p_tipo)
    ORDER BY m.created_at DESC, m.id DESC
    LIMIT COALESCE(p_limite, 500);
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_liquidaciones(
    p_id_tienda bigint,
    p_desde     date DEFAULT NULL,
    p_hasta     date DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NOT public.fn_user_can_access_tienda(p_id_tienda) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', p_id_tienda USING ERRCODE = '42501';
    END IF;

    RETURN COALESCE((
        SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at DESC)
        FROM (
            SELECT l.*,
                   c.nombre AS cuenta_destino, co.denominacion AS concepto_destino,
                   (SELECT jsonb_agg(to_jsonb(d)) FROM public.fdi_dat_liquidacion_detalle d
                    WHERE d.id_liquidacion = l.id) AS detalle,
                   (SELECT count(*) FROM public.fdi_dat_liquidacion_orden lo
                    WHERE lo.id_liquidacion = l.id) AS ordenes_count
            FROM public.fdi_dat_liquidacion l
            JOIN public.fdi_dat_cuenta c   ON c.id = l.id_cuenta_destino
            JOIN public.fdi_dat_concepto co ON co.id = c.id_concepto
            WHERE l.id_tienda = p_id_tienda
              AND (p_desde IS NULL OR l.created_at::date >= p_desde)
              AND (p_hasta IS NULL OR l.created_at::date <= p_hasta)
        ) x
    ), '[]'::jsonb);
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_inversiones(
    p_id_tienda        bigint,
    p_estado           varchar DEFAULT NULL,
    p_solo_revision    boolean DEFAULT false
) RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NOT public.fn_user_can_access_tienda(p_id_tienda) THEN
