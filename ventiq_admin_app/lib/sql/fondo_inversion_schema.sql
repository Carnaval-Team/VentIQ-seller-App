        FROM (
            SELECT i.*,
                   -- Revisión por vencimiento calculada al consultar.
                   (i.requiere_revision OR (
                       i.estado <> 'completado'
                       AND i.created_at < now() - make_interval(
                           days => COALESCE((SELECT cfg.dias_alerta_revision
                                             FROM public.fdi_dat_config cfg
                                             WHERE cfg.id_tienda = p_id_tienda), 15))
                   )) AS en_revision,
                   CASE
                       WHEN i.requiere_revision THEN i.motivo_revision
                       WHEN i.estado <> 'completado'
                            AND i.created_at < now() - make_interval(
                                days => COALESCE((SELECT cfg.dias_alerta_revision
                                                  FROM public.fdi_dat_config cfg
                                                  WHERE cfg.id_tienda = p_id_tienda), 15))
                       THEN 'vencida'
                   END AS motivo_revision_efectivo
            FROM public.fdi_dat_inversion i
            WHERE i.id_tienda = p_id_tienda
        ) x
        WHERE (p_estado IS NULL OR x.estado = p_estado)
          AND (NOT p_solo_revision OR x.en_revision)
    ), '[]'::jsonb);
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_detalle_inversion(p_id_inversion bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_inv record;
BEGIN
    SELECT * INTO v_inv FROM public.fdi_dat_inversion WHERE id = p_id_inversion;
    IF v_inv.id IS NULL THEN
        RAISE EXCEPTION 'Inversión % no encontrada', p_id_inversion USING ERRCODE = 'P0002';
    END IF;
    IF NOT public.fn_user_can_access_tienda(v_inv.id_tienda) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', v_inv.id_tienda USING ERRCODE = '42501';
    END IF;

    RETURN jsonb_build_object(
        'inversion', to_jsonb(v_inv),
        'fuentes', COALESCE((
            SELECT jsonb_agg(to_jsonb(f))
            FROM (
                SELECT fs.*, c.nombre AS cuenta, co.denominacion AS concepto,
                       mp.denominacion AS medio_pago
                FROM public.fdi_dat_inversion_fuente fs
                JOIN public.fdi_dat_cuenta c   ON c.id = fs.id_cuenta
                JOIN public.fdi_dat_concepto co ON co.id = c.id_concepto
                LEFT JOIN public.app_nom_medio_pago mp ON mp.id = fs.id_medio_pago
                WHERE fs.id_inversion = p_id_inversion) f), '[]'::jsonb),
        'recepciones', COALESCE((
            SELECT jsonb_agg(to_jsonb(r))
            FROM public.fdi_dat_inversion_recepcion r
            WHERE r.id_inversion = p_id_inversion), '[]'::jsonb),
        'historial', COALESCE((
            SELECT jsonb_agg(to_jsonb(h) ORDER BY h.created_at)
            FROM public.fdi_hist_estado_inversion h
            WHERE h.id_inversion = p_id_inversion), '[]'::jsonb)
    );
END;
$$;

