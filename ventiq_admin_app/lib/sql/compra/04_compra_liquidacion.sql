-- ============================================================================
-- 04_compra_liquidacion.sql — Fase 4: reserva y pago de la compra (carril A)
--
-- REQUIERE: 03a y 03b aplicados.
--
-- Modelo:
--   reservar  → crea reservas por (cuenta, medio, moneda) en moneda NATIVA.
--               No mueve saldo. Estado: crecida → reservada.
--   pagar     → consume las reservas y debita el saldo en la MISMA transacción.
--               Estado: reservada → pagada.
--   liberar   → suelta las reservas sin mover dinero. Vuelve a crecida.
--   anular    → devuelve al fondo lo pagado (contramovimiento) y deja anulada.
--
-- Reglas de dinero que implementa:
--   · Se reserva en moneda nativa; el equivalente a la moneda del total se
--     guarda aparte y solo sirve para validar cobertura.
--   · La suma de equivalentes debe igualar `total_financiado` al centavo.
--   · El disponible se valida SIEMPRE por (cuenta, medio, moneda), nunca por
--     el total consolidado del fondo.
--   · `total_financiado` no se puede tocar con la compra reservada o pagada.
--
-- ROLLBACK: 04_compra_liquidacion_rollback.sql
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Esquema
-- ---------------------------------------------------------------------------
CREATE TABLE public.fdi_dat_compra_reserva (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra       bigint NOT NULL REFERENCES public.fdi_dat_compra(id) ON DELETE CASCADE,
    id_tienda       bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_cuenta       bigint NOT NULL REFERENCES public.fdi_dat_cuenta(id),
    id_medio_pago   smallint NOT NULL REFERENCES public.app_nom_medio_pago(id),
    moneda          text NOT NULL,
    monto           numeric(14,2) NOT NULL CHECK (monto > 0),
    tasa_a_total    numeric(18,10) NOT NULL DEFAULT 1 CHECK (tasa_a_total > 0),
    monto_eq_total  numeric(14,2) NOT NULL,
    estado          text NOT NULL DEFAULT 'activa'
                    CHECK (estado IN ('activa','consumida','liberada')),
    id_movimiento   bigint REFERENCES public.fdi_dat_movimiento(id),
    idempotency_key uuid,
    created_by      uuid,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_fdi_reserva_compra ON public.fdi_dat_compra_reserva (id_compra, estado);
CREATE INDEX idx_fdi_reserva_clave ON public.fdi_dat_compra_reserva (id_cuenta, id_medio_pago, moneda)
    WHERE estado = 'activa';

CREATE TABLE public.fdi_dat_compra_pago (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra       bigint NOT NULL REFERENCES public.fdi_dat_compra(id) ON DELETE CASCADE,
    id_tienda       bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_cuenta       bigint NOT NULL REFERENCES public.fdi_dat_cuenta(id),
    id_medio_pago   smallint NOT NULL REFERENCES public.app_nom_medio_pago(id),
    moneda          text NOT NULL,
    monto           numeric(14,2) NOT NULL CHECK (monto > 0),
    tasa_a_total    numeric(18,10) NOT NULL DEFAULT 1 CHECK (tasa_a_total > 0),
    monto_eq_total  numeric(14,2) NOT NULL,
    origen          text NOT NULL DEFAULT 'fondo' CHECK (origen IN ('fondo','aporte')),
    id_aporte       bigint,
    id_movimiento   bigint REFERENCES public.fdi_dat_movimiento(id),
    idempotency_key uuid,
    created_by      uuid,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_fdi_pago_compra ON public.fdi_dat_compra_pago (id_compra);

ALTER TABLE public.fdi_dat_movimiento
    ADD COLUMN IF NOT EXISTS id_compra bigint REFERENCES public.fdi_dat_compra(id),
    ADD COLUMN IF NOT EXISTS tasa numeric(18,10);

ALTER TABLE public.fdi_dat_movimiento
    DROP CONSTRAINT IF EXISTS fdi_dat_movimiento_tipo_check;
ALTER TABLE public.fdi_dat_movimiento
    ADD CONSTRAINT fdi_dat_movimiento_tipo_check
    CHECK (tipo IN ('liquidacion','transferencia_salida','transferencia_entrada',
                    'comision_transferencia','extraccion_inversion','ingreso_manual',
                    'ajuste','ajuste_correccion','gasto','devolucion_inversion',
                    'pago_compra','devolucion_compra'));

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['fdi_dat_compra_reserva','fdi_dat_compra_pago']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_select', t);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (public.fn_user_can_access_tienda(id_tienda))', t || '_select', t);
        EXECUTE format('GRANT SELECT ON public.%I TO authenticated', t);
    END LOOP;
END;
$$;

-- ---------------------------------------------------------------------------
-- 2) Aplicador con `id_compra` y `tasa` (12 args, una sola firma)
-- ---------------------------------------------------------------------------
DROP FUNCTION IF EXISTS public._fdi_aplicar_movimiento(
    bigint, bigint, smallint, text, numeric, character varying, bigint, bigint, bigint, text, uuid);

CREATE OR REPLACE FUNCTION public._fdi_aplicar_movimiento(
    p_id_tienda        bigint,
    p_id_cuenta        bigint,
    p_id_medio_pago    smallint,
    p_moneda           text,
    p_delta            numeric,
    p_tipo             character varying,
    p_id_liquidacion   bigint DEFAULT NULL,
    p_id_transferencia bigint DEFAULT NULL,
    p_id_inversion     bigint DEFAULT NULL,
    p_observacion      text   DEFAULT NULL,
    p_idempotency_key  uuid   DEFAULT NULL,
    p_id_compra        bigint DEFAULT NULL,
    p_tasa             numeric DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_saldo_id     bigint;
    v_saldo_tienda bigint;
    v_saldo_previo numeric;
    v_saldo_nuevo  numeric;
    v_mov          bigint;
    v_moneda       text := upper(btrim(coalesce(p_moneda, '')));
BEGIN
    IF v_moneda = '' THEN
        RAISE EXCEPTION 'La moneda es obligatoria' USING ERRCODE = '22023';
    END IF;
    IF p_delta IS NULL OR p_delta <> round(p_delta, 2) THEN
        RAISE EXCEPTION 'El monto debe tener como máximo dos decimales (recibido %)', p_delta
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.fdi_dat_cuenta c
                    WHERE c.id = p_id_cuenta AND c.id_tienda = p_id_tienda) THEN
        RAISE EXCEPTION 'La cuenta % no pertenece a la tienda %', p_id_cuenta, p_id_tienda
            USING ERRCODE = '42501';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.app_nom_medio_pago m WHERE m.id = p_id_medio_pago) THEN
        RAISE EXCEPTION 'El medio de pago % no existe', p_id_medio_pago USING ERRCODE = 'P0002';
    END IF;

    SELECT id, id_tienda, saldo INTO v_saldo_id, v_saldo_tienda, v_saldo_previo
    FROM public.fdi_dat_saldo
    WHERE id_cuenta = p_id_cuenta AND id_medio_pago = p_id_medio_pago AND moneda = v_moneda
    FOR UPDATE;

    IF v_saldo_id IS NULL THEN
        INSERT INTO public.fdi_dat_saldo (id_tienda, id_cuenta, id_medio_pago, moneda, saldo)
        VALUES (p_id_tienda, p_id_cuenta, p_id_medio_pago, v_moneda, 0)
        RETURNING id, saldo INTO v_saldo_id, v_saldo_previo;
    ELSIF v_saldo_tienda <> p_id_tienda THEN
        RAISE EXCEPTION 'El saldo de la cuenta % pertenece a otra tienda', p_id_cuenta
            USING ERRCODE = '42501';
    END IF;

    v_saldo_nuevo := round(v_saldo_previo + p_delta, 2);
    IF v_saldo_nuevo < 0 THEN
        RAISE EXCEPTION 'Saldo insuficiente en cuenta %, medio %, moneda %: disponible %, requerido %',
            p_id_cuenta, p_id_medio_pago, v_moneda, v_saldo_previo, -p_delta
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public.fdi_dat_saldo SET saldo = v_saldo_nuevo, updated_at = now() WHERE id = v_saldo_id;

    INSERT INTO public.fdi_dat_movimiento (
        id_tienda, id_cuenta, id_medio_pago, moneda, monto,
        saldo_anterior, saldo_nuevo, tipo,
        id_liquidacion, id_transferencia, id_inversion,
        observacion, created_by, idempotency_key, id_compra, tasa
    ) VALUES (
        p_id_tienda, p_id_cuenta, p_id_medio_pago, v_moneda, round(p_delta, 2),
        v_saldo_previo, v_saldo_nuevo, p_tipo,
        p_id_liquidacion, p_id_transferencia, p_id_inversion,
        p_observacion, auth.uid(), p_idempotency_key, p_id_compra, p_tasa
    ) RETURNING id INTO v_mov;

    RETURN v_mov;
END;
$$;

REVOKE ALL ON FUNCTION public._fdi_aplicar_movimiento(
    bigint, bigint, smallint, text, numeric, character varying, bigint, bigint, bigint, text, uuid, bigint, numeric)
    FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3) Disponible por (cuenta, medio, moneda)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_disponible(p_id_tienda bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v jsonb;
BEGIN
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_can_access_tienda(p_id_tienda), false) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', p_id_tienda USING ERRCODE = '42501';
    END IF;

    WITH s AS (
        SELECT s.id_cuenta, s.id_medio_pago, s.moneda, s.saldo,
               c.nombre AS cuenta, mp.denominacion AS medio_pago
        FROM public.fdi_dat_saldo s
        JOIN public.fdi_dat_cuenta c ON c.id = s.id_cuenta
        JOIN public.app_nom_medio_pago mp ON mp.id = s.id_medio_pago
        WHERE s.id_tienda = p_id_tienda
    ), r AS (
        SELECT id_cuenta, id_medio_pago, moneda, sum(monto) AS reservado
        FROM public.fdi_dat_compra_reserva
        WHERE id_tienda = p_id_tienda AND estado = 'activa'
        GROUP BY 1,2,3
    )
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
                'id_cuenta', s.id_cuenta,
                'cuenta', s.cuenta,
                'id_medio_pago', s.id_medio_pago,
                'medio_pago', s.medio_pago,
                'moneda', s.moneda,
                'saldo', s.saldo,
                'reservado', COALESCE(r.reservado, 0),
                'disponible', round(s.saldo - COALESCE(r.reservado, 0), 2)
            ) ORDER BY s.id_cuenta, s.id_medio_pago, s.moneda), '[]'::jsonb)
      INTO v
    FROM s LEFT JOIN r USING (id_cuenta, id_medio_pago, moneda);

    RETURN v;
END;
$$;

-- ---------------------------------------------------------------------------
-- 4) Reservar
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_compra_reservar(
    p_id_compra       bigint,
    p_fuentes         jsonb,
    p_idempotency_key uuid DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_c        record;
    v_fuente   jsonb;
    v_cubierto numeric := 0;
    v_disp     numeric;
    v_monto    numeric;
    v_tasa     numeric;
BEGIN
    SELECT * INTO v_c FROM public.fdi_dat_compra WHERE id = p_id_compra FOR UPDATE;
    IF v_c.id IS NULL THEN
        RAISE EXCEPTION 'Compra % no encontrada', p_id_compra USING ERRCODE = 'P0002';
    END IF;
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_is_gerente_or_superadmin(v_c.id_tienda), false) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF v_c.estado <> 'creada' THEN
        RAISE EXCEPTION 'Solo se reserva una compra en estado creada (actual: %)', v_c.estado
            USING ERRCODE = '22023';
    END IF;
    IF v_c.modo_liquidacion <> 'fondo' THEN
        RAISE EXCEPTION 'Esta compra se liquida con inversores; no se reserva del fondo'
            USING ERRCODE = '22023';
    END IF;
    IF v_c.total_financiado <= 0 THEN
        RAISE EXCEPTION 'La compra no tiene total a financiar' USING ERRCODE = '22023';
    END IF;
    IF p_fuentes IS NULL OR jsonb_typeof(p_fuentes) IS DISTINCT FROM 'array'
       OR jsonb_array_length(p_fuentes) = 0 THEN
        RAISE EXCEPTION 'Seleccione al menos una fuente del fondo' USING ERRCODE = '22023';
    END IF;

    FOR v_fuente IN SELECT * FROM jsonb_array_elements(p_fuentes) LOOP
        v_monto := (v_fuente->>'monto')::numeric;
        v_tasa  := COALESCE((v_fuente->>'tasa_a_total')::numeric, 1);
        IF v_monto IS NULL OR v_monto <= 0 OR v_monto <> round(v_monto, 2)
           OR v_tasa IS NULL OR v_tasa <= 0 THEN
            RAISE EXCEPTION 'Fuente inválida: monto y tasa deben ser > 0 y de dos decimales'
                USING ERRCODE = '22023';
        END IF;
        IF (v_fuente->>'moneda') = v_c.moneda_total THEN
            v_tasa := 1;
        END IF;

        SELECT round(s.saldo - COALESCE((
                   SELECT sum(r.monto) FROM public.fdi_dat_compra_reserva r
                   WHERE r.id_cuenta = s.id_cuenta AND r.id_medio_pago = s.id_medio_pago
                     AND r.moneda = s.moneda AND r.estado = 'activa'), 0), 2)
          INTO v_disp
        FROM public.fdi_dat_saldo s
        WHERE s.id_tienda = v_c.id_tienda
          AND s.id_cuenta = (v_fuente->>'id_cuenta')::bigint
          AND s.id_medio_pago = (v_fuente->>'id_medio_pago')::smallint
          AND s.moneda = v_fuente->>'moneda'
        FOR UPDATE OF s;

        IF v_disp IS NULL THEN
            RAISE EXCEPTION 'No existe saldo para la cuenta/medio/moneda indicados'
                USING ERRCODE = 'P0002';
        END IF;
        IF v_disp < v_monto THEN
            RAISE EXCEPTION 'Disponible insuficiente en % (cuenta %): hay %, se piden %',
                v_fuente->>'moneda', v_fuente->>'id_cuenta', v_disp, v_monto
                USING ERRCODE = 'P0002';
        END IF;

        INSERT INTO public.fdi_dat_compra_reserva (
            id_compra, id_tienda, id_cuenta, id_medio_pago, moneda,
            monto, tasa_a_total, monto_eq_total, estado, idempotency_key, created_by
        ) VALUES (
            p_id_compra, v_c.id_tienda,
            (v_fuente->>'id_cuenta')::bigint,
            (v_fuente->>'id_medio_pago')::smallint,
            upper(btrim(v_fuente->>'moneda')),
            v_monto, v_tasa, round(v_monto * v_tasa, 2), 'activa',
            p_idempotency_key, auth.uid()
        );

        v_cubierto := v_cubierto + round(v_monto * v_tasa, 2);
    END LOOP;

    IF v_cubierto <> v_c.total_financiado THEN
        RAISE EXCEPTION 'Las fuentes cubren % y la compra necesita %: la diferencia debe ser 0',
            v_cubierto, v_c.total_financiado USING ERRCODE = '22023';
    END IF;

    UPDATE public.fdi_dat_compra
       SET estado = 'reservada', updated_at = now()
     WHERE id = p_id_compra;

    INSERT INTO public.fdi_hist_estado_compra
        (id_compra, id_tienda, estado_anterior, estado_nuevo, origen, motivo, created_by)
    VALUES (p_id_compra, v_c.id_tienda, 'creada', 'reservada', 'automatico',
            'Reserva de fondos', auth.uid());

    RETURN jsonb_build_object('status','ok','id_compra',p_id_compra,
        'estado','reservada','cubierto',v_cubierto,'total_financiado',v_c.total_financiado);
END;
$$;

-- ---------------------------------------------------------------------------
-- 5) Pagar (consume reservas y debita, en la misma transacción)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_compra_pagar(
    p_id_compra bigint,
    p_tasa_pago numeric DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_c     record;
    v_r     record;
    v_mov   bigint;
    v_total numeric := 0;
BEGIN
    SELECT * INTO v_c FROM public.fdi_dat_compra WHERE id = p_id_compra FOR UPDATE;
    IF v_c.id IS NULL THEN
        RAISE EXCEPTION 'Compra % no encontrada', p_id_compra USING ERRCODE = 'P0002';
    END IF;
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_is_gerente_or_superadmin(v_c.id_tienda), false) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF v_c.estado = 'pagada' THEN
        RETURN jsonb_build_object('status','ok','duplicada',true,'id_compra',p_id_compra);
    END IF;
    IF v_c.estado <> 'reservada' THEN
        RAISE EXCEPTION 'Solo se paga una compra reservada (actual: %)', v_c.estado
            USING ERRCODE = '22023';
    END IF;

    -- 1) validar que las reservas siguen cubriendo el total
    SELECT COALESCE(sum(monto_eq_total), 0) INTO v_total
    FROM public.fdi_dat_compra_reserva
    WHERE id_compra = p_id_compra AND estado = 'activa';

    IF v_total <> v_c.total_financiado THEN
        RAISE EXCEPTION 'Las reservas cubren % y la compra necesita %', v_total, v_c.total_financiado
            USING ERRCODE = '22023';
    END IF;

    -- 2) consumir cada reserva y debitar
    FOR v_r IN
        SELECT * FROM public.fdi_dat_compra_reserva
        WHERE id_compra = p_id_compra AND estado = 'activa'
        ORDER BY id
    LOOP
        v_mov := public._fdi_aplicar_movimiento(
            v_c.id_tienda, v_r.id_cuenta, v_r.id_medio_pago, v_r.moneda,
            -v_r.monto, 'pago_compra',
            p_observacion := 'Pago compra #' || v_c.numero_compra,
            p_id_compra := p_id_compra,
            p_tasa := v_r.tasa_a_total);

        UPDATE public.fdi_dat_compra_reserva
           SET estado = 'consumida', id_movimiento = v_mov, updated_at = now()
         WHERE id = v_r.id;

        INSERT INTO public.fdi_dat_compra_pago (
            id_compra, id_tienda, id_cuenta, id_medio_pago, moneda,
            monto, tasa_a_total, monto_eq_total, origen, id_movimiento, created_by
        ) VALUES (
            p_id_compra, v_c.id_tienda, v_r.id_cuenta, v_r.id_medio_pago, v_r.moneda,
            v_r.monto, v_r.tasa_a_total, v_r.monto_eq_total, 'fondo', v_mov, auth.uid()
        );
    END LOOP;

    UPDATE public.fdi_dat_compra SET estado = 'pagada', updated_at = now()
     WHERE id = p_id_compra;

    INSERT INTO public.fdi_hist_estado_compra
        (id_compra, id_tienda, estado_anterior, estado_nuevo, origen, motivo, created_by)
    VALUES (p_id_compra, v_c.id_tienda, 'reservada', 'pagada', 'automatico',
            'Pago de la compra', auth.uid());

    RETURN jsonb_build_object('status','ok','id_compra',p_id_compra,'estado','pagada',
        'pagado',v_total);
END;
$$;

-- ---------------------------------------------------------------------------
-- 6) Liberar reservas (sin mover dinero)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_compra_liberar(
    p_id_compra bigint,
    p_motivo    text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_c record;
    v_n integer;
BEGIN
    IF p_motivo IS NULL OR btrim(p_motivo) = '' THEN
        RAISE EXCEPTION 'El motivo es obligatorio' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_c FROM public.fdi_dat_compra WHERE id = p_id_compra FOR UPDATE;
    IF v_c.id IS NULL THEN
        RAISE EXCEPTION 'Compra % no encontrada', p_id_compra USING ERRCODE = 'P0002';
    END IF;
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_is_gerente_or_superadmin(v_c.id_tienda), false) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF v_c.estado <> 'reservada' THEN
        RAISE EXCEPTION 'Solo se liberan reservas de una compra reservada (actual: %)', v_c.estado
            USING ERRCODE = '22023';
    END IF;

    UPDATE public.fdi_dat_compra_reserva
       SET estado = 'liberada', updated_at = now()
     WHERE id_compra = p_id_compra AND estado = 'activa';
    GET DIAGNOSTICS v_n = ROW_COUNT;

    UPDATE public.fdi_dat_compra SET estado = 'creada', updated_at = now()
     WHERE id = p_id_compra;

    INSERT INTO public.fdi_hist_estado_compra
        (id_compra, id_tienda, estado_anterior, estado_nuevo, origen, motivo, created_by)
    VALUES (p_id_compra, v_c.id_tienda, 'reservada', 'creada', 'manual', btrim(p_motivo), auth.uid());

    RETURN jsonb_build_object('status','ok','id_compra',p_id_compra,'liberadas',v_n,'estado','creada');
END;
$$;

-- ---------------------------------------------------------------------------
-- 7) Anular una compra pagada (devuelve el dinero)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_compra_anular(
    p_id_compra bigint,
    p_motivo    text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_c       record;
    v_p       record;
    v_devuelto numeric := 0;
BEGIN
    IF p_motivo IS NULL OR btrim(p_motivo) = '' THEN
        RAISE EXCEPTION 'El motivo es obligatorio' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_c FROM public.fdi_dat_compra WHERE id = p_id_compra FOR UPDATE;
    IF v_c.id IS NULL THEN
        RAISE EXCEPTION 'Compra % no encontrada', p_id_compra USING ERRCODE = 'P0002';
    END IF;
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_is_gerente_or_superadmin(v_c.id_tienda), false) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF v_c.estado = 'anulada' THEN
        RETURN jsonb_build_object('status','ok','duplicada',true,'devuelto',0);
    END IF;
    IF v_c.estado <> 'pagada' THEN
        RAISE EXCEPTION 'Solo se anula una compra pagada (actual: %)', v_c.estado
            USING ERRCODE = '22023';
    END IF;
    IF EXISTS (SELECT 1 FROM public.fdi_dat_compra_recepcion WHERE id_compra = p_id_compra) THEN
        RAISE EXCEPTION 'La compra ya tiene recepciones; no se anula sin resolver el inventario'
            USING ERRCODE = '22023';
    END IF;

    FOR v_p IN SELECT * FROM public.fdi_dat_compra_pago WHERE id_compra = p_id_compra ORDER BY id LOOP
        PERFORM public._fdi_aplicar_movimiento(
            v_c.id_tienda, v_p.id_cuenta, v_p.id_medio_pago, v_p.moneda,
            v_p.monto, 'devolucion_compra',
            p_observacion := 'Anulación compra #' || v_c.numero_compra || '. Motivo: ' || btrim(p_motivo),
            p_id_compra := p_id_compra,
            p_tasa := v_p.tasa_a_total);
        v_devuelto := v_devuelto + v_p.monto;
    END LOOP;

    UPDATE public.fdi_dat_compra SET estado = 'anulada', updated_at = now()
     WHERE id = p_id_compra;

    INSERT INTO public.fdi_hist_estado_compra
        (id_compra, id_tienda, estado_anterior, estado_nuevo, origen, motivo, created_by)
    VALUES (p_id_compra, v_c.id_tienda, 'pagada', 'anulada', 'manual', btrim(p_motivo), auth.uid());

    RETURN jsonb_build_object('status','ok','id_compra',p_id_compra,'estado','anulada',
        'devuelto',v_devuelto);
END;
$$;

-- ---------------------------------------------------------------------------
-- 8) Cancelar también desde 'reservada' (libera y cancela)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_compra_cancelar(p_id_compra bigint, p_motivo text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_c record;
BEGIN
    IF p_motivo IS NULL OR btrim(p_motivo) = '' THEN
        RAISE EXCEPTION 'El motivo de cancelación es obligatorio' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_c FROM public.fdi_dat_compra WHERE id = p_id_compra FOR UPDATE;
    IF v_c.id IS NULL THEN
        RAISE EXCEPTION 'Compra % no encontrada', p_id_compra USING ERRCODE = 'P0002';
    END IF;
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_is_gerente_or_superadmin(v_c.id_tienda), false) THEN
        RAISE EXCEPTION 'Solo gerente o superadmin' USING ERRCODE = '42501';
    END IF;
    IF v_c.estado = 'cancelada' THEN
        RETURN jsonb_build_object('status','ok','duplicada',true);
    END IF;
    IF v_c.estado NOT IN ('creada','reservada') THEN
        RAISE EXCEPTION 'Solo se cancela una compra creada o reservada (actual: %). Si está pagada, usar anular.',
            v_c.estado USING ERRCODE = '22023';
    END IF;
    IF EXISTS (SELECT 1 FROM public.fdi_dat_compra_recepcion WHERE id_compra = p_id_compra) THEN
        RAISE EXCEPTION 'La compra ya tiene recepciones' USING ERRCODE = '22023';
    END IF;

    UPDATE public.fdi_dat_compra_reserva
       SET estado = 'liberada', updated_at = now()
     WHERE id_compra = p_id_compra AND estado = 'activa';

    UPDATE public.fdi_dat_compra SET estado = 'cancelada', updated_at = now() WHERE id = p_id_compra;

    INSERT INTO public.fdi_hist_estado_compra
        (id_compra, id_tienda, estado_anterior, estado_nuevo, origen, motivo, created_by)
    VALUES (p_id_compra, v_c.id_tienda, v_c.estado, 'cancelada', 'manual', btrim(p_motivo), auth.uid());

    RETURN jsonb_build_object('status','ok','id_compra',p_id_compra,'estado','cancelada');
END;
$$;

REVOKE ALL ON FUNCTION public.fn_fdi_disponible(bigint) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_fdi_compra_reservar(bigint, jsonb, uuid) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_fdi_compra_pagar(bigint, numeric) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_fdi_compra_liberar(bigint, text) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_fdi_compra_anular(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_fdi_disponible(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_fdi_compra_reservar(bigint, jsonb, uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_fdi_compra_pagar(bigint, numeric) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_fdi_compra_liberar(bigint, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_fdi_compra_anular(bigint, text) TO authenticated;

DO $$
DECLARE v integer;
BEGIN
    SELECT count(*) INTO v FROM information_schema.tables
    WHERE table_schema='public' AND table_name IN ('fdi_dat_compra_reserva','fdi_dat_compra_pago');
    IF v <> 2 THEN RAISE EXCEPTION 'Faltan tablas de liquidación'; END IF;

    SELECT count(*) INTO v FROM information_schema.columns
    WHERE table_schema='public' AND table_name='fdi_dat_movimiento'
      AND column_name IN ('id_compra','tasa');
    IF v <> 2 THEN RAISE EXCEPTION 'Faltan columnas id_compra/tasa en el ledger'; END IF;

    SELECT count(*) INTO v FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname='_fdi_aplicar_movimiento';
    IF v <> 1 THEN RAISE EXCEPTION 'Quedaron % firmas de _fdi_aplicar_movimiento', v; END IF;

    SELECT count(*) INTO v FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname IN ('fn_fdi_disponible','fn_fdi_compra_reservar',
        'fn_fdi_compra_pagar','fn_fdi_compra_liberar','fn_fdi_compra_anular');
    IF v <> 5 THEN RAISE EXCEPTION 'Faltan RPC de liquidación: % de 5', v; END IF;
END;
$$;

