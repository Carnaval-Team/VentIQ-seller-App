-- ============================================================================
-- 08b_conciliacion_job.sql — Fase 8: la conciliación (R1) corre sola y deja
-- rastro
--
-- QUÉ HACE
--   `docs/planes/fondo-inversion/02-contabilidad.md` §6.3 lo exige: **R1 no es
--   un dashboard que nadie mira, tiene que correr solo y fallar ruidosamente**.
--   Hasta ahora `fn_fdi_conciliacion(tienda)` existía pero solo se ejecutaba si
--   alguien abría la pantalla.
--
--   1. Tabla `fdi_dat_conciliacion_ejecucion`: una fila por tienda y corrida,
--      con claves, descuadres, diferencia total y el detalle completo.
--   2. `fn_fdi_conciliacion_registrar()`: recorre todas las tiendas con saldo,
--      corre R1, guarda la fila y poda lo que tenga más de 90 días.
--   3. `fn_fdi_conciliacion_ultima(p_id_tienda)`: lo que lee la UI para la nota
--      «última revisión automática».
--   4. Job de `pg_cron` `fdi-conciliacion-diaria` a las 03:00.
--
-- NO toca `fn_fdi_conciliacion` (R1 sigue siendo una sola verdad), ni
-- `fdi_dat_saldo`, ni `fdi_dat_movimiento`. Solo lee.
--
-- IDEMPOTENTE: se puede reaplicar; reprograma el job en vez de duplicarlo.
-- REQUIERE: `fn_fdi_conciliacion(bigint)` (fase 1) y la extensión `pg_cron`.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Bitácora de corridas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fdi_dat_conciliacion_ejecucion (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda        bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    ejecutada_at     timestamptz NOT NULL DEFAULT now(),
    claves           integer NOT NULL CHECK (claves >= 0),
    descuadres       integer NOT NULL CHECK (descuadres >= 0),
    diferencia_total numeric(16,2) NOT NULL DEFAULT 0
                     CHECK (diferencia_total >= 0),
    origen           text NOT NULL DEFAULT 'cron'
                     CHECK (origen IN ('cron','manual')),
    detalle          jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_fdi_conciliacion_ejec_tienda
    ON public.fdi_dat_conciliacion_ejecucion (id_tienda, ejecutada_at DESC);

ALTER TABLE public.fdi_dat_conciliacion_ejecucion ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS fdi_conciliacion_ejec_select ON public.fdi_dat_conciliacion_ejecucion;
CREATE POLICY fdi_conciliacion_ejec_select ON public.fdi_dat_conciliacion_ejecucion
    FOR SELECT TO authenticated
    USING (public.fn_user_can_access_tienda(id_tienda));

GRANT SELECT ON public.fdi_dat_conciliacion_ejecucion TO authenticated;

-- ---------------------------------------------------------------------------
-- 2) Correr y registrar
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_conciliacion_registrar()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_t          record;
    v_c          jsonb;
    v_claves     integer;
    v_desc       integer;
    v_dif        numeric := 0;
    v_tiendas    integer := 0;
    v_desc_total integer := 0;
    v_dif_total  numeric := 0;
    v_borradas   integer := 0;
BEGIN
    FOR v_t IN SELECT DISTINCT s.id_tienda FROM public.fdi_dat_saldo s ORDER BY 1 LOOP
        v_c      := public.fn_fdi_conciliacion(v_t.id_tienda);
        v_claves := COALESCE((v_c ->> 'claves')::integer, 0);
        v_desc   := COALESCE((v_c ->> 'descuadres')::integer, 0);

        -- Diferencia total = suma de las dos desviaciones en valor absoluto, para
        -- que un descuadre a favor no tape uno en contra.
        SELECT COALESCE(sum(
                   abs(COALESCE((f ->> 'dif_saldo_vs_mov')::numeric, 0))
                 + abs(COALESCE((f ->> 'dif_saldo_vs_ultimo')::numeric, 0))), 0)
          INTO v_dif
          FROM jsonb_array_elements(COALESCE(v_c -> 'filas', '[]'::jsonb)) f;

        INSERT INTO public.fdi_dat_conciliacion_ejecucion
            (id_tienda, claves, descuadres, diferencia_total, origen, detalle)
        VALUES (v_t.id_tienda, v_claves, v_desc, round(v_dif, 2), 'cron', v_c);

        v_tiendas    := v_tiendas + 1;
        v_desc_total := v_desc_total + v_desc;
        v_dif_total  := v_dif_total + v_dif;
    END LOOP;

    DELETE FROM public.fdi_dat_conciliacion_ejecucion
     WHERE ejecutada_at < now() - interval '90 days';
    GET DIAGNOSTICS v_borradas = ROW_COUNT;

    RETURN jsonb_build_object(
        'status', 'ok',
        'tiendas', v_tiendas,
        'descuadres', v_desc_total,
        'diferencia_total', round(v_dif_total, 2),
        'podadas', v_borradas,
        'ejecutada_at', now());
END;
$$;

-- ---------------------------------------------------------------------------
-- 3) Lo que lee la UI
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_conciliacion_ultima(p_id_tienda bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_e record;
BEGIN
    IF auth.uid() IS NOT NULL
       AND NOT COALESCE(public.fn_user_can_access_tienda(p_id_tienda), false) THEN
        RAISE EXCEPTION 'Sin acceso a la tienda %', p_id_tienda USING ERRCODE = '42501';
    END IF;

    SELECT e.ejecutada_at, e.claves, e.descuadres, e.diferencia_total, e.origen
      INTO v_e
      FROM public.fdi_dat_conciliacion_ejecucion e
     WHERE e.id_tienda = p_id_tienda
     ORDER BY e.ejecutada_at DESC
     LIMIT 1;

    IF v_e.ejecutada_at IS NULL THEN
        RETURN NULL; -- nunca se ha corrido: la UI no inventa una fecha
    END IF;

    RETURN jsonb_build_object(
        'ejecutada_at',     v_e.ejecutada_at,
        'claves',           v_e.claves,
        'descuadres',       v_e.descuadres,
        'diferencia_total', v_e.diferencia_total,
        'origen',           v_e.origen);
END;
$$;

-- ---------------------------------------------------------------------------
-- 4) El job
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_jobid bigint;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
        RAISE NOTICE '08b: pg_cron no está instalado; la tabla y las RPC quedan, el job no.';
        RETURN;
    END IF;

    FOR v_jobid IN SELECT jobid FROM cron.job WHERE jobname = 'fdi-conciliacion-diaria' LOOP
        PERFORM cron.unschedule(v_jobid);
    END LOOP;

    PERFORM cron.schedule(
        'fdi-conciliacion-diaria',
        '0 3 * * *',
        'SELECT public.fn_fdi_conciliacion_registrar()');
END;
$$;

-- ---------------------------------------------------------------------------
-- 5) Permisos
-- ---------------------------------------------------------------------------
REVOKE ALL ON FUNCTION public.fn_fdi_conciliacion_registrar() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.fn_fdi_conciliacion_ultima(bigint) FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.fn_fdi_conciliacion_registrar() TO service_role;
GRANT EXECUTE ON FUNCTION public.fn_fdi_conciliacion_ultima(bigint) TO authenticated;

-- ---------------------------------------------------------------------------
-- 6) Verificación del archivo
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_n integer;
BEGIN
    IF to_regclass('public.fdi_dat_conciliacion_ejecucion') IS NULL THEN
        RAISE EXCEPTION '08b: no se creó fdi_dat_conciliacion_ejecucion';
    END IF;

    IF to_regprocedure('public.fn_fdi_conciliacion_registrar()') IS NULL THEN
        RAISE EXCEPTION '08b: falta fn_fdi_conciliacion_registrar()';
    END IF;
    IF to_regprocedure('public.fn_fdi_conciliacion_ultima(bigint)') IS NULL THEN
        RAISE EXCEPTION '08b: falta fn_fdi_conciliacion_ultima(bigint)';
    END IF;

    SELECT count(*) INTO v_n FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND p.proname IN ('fn_fdi_conciliacion','fn_fdi_conciliacion_registrar',
                         'fn_fdi_conciliacion_ultima');
    IF v_n <> 3 THEN
        RAISE EXCEPTION '08b: se esperaban 3 funciones de conciliación, hay %', v_n;
    END IF;

    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
        SELECT count(*) INTO v_n FROM cron.job WHERE jobname = 'fdi-conciliacion-diaria';
        IF v_n <> 1 THEN
            RAISE EXCEPTION '08b: el job fdi-conciliacion-diaria debería existir una vez (hay %)', v_n;
        END IF;
    END IF;

    RAISE NOTICE '08b: conciliación programada (tabla, 2 RPC y job diario a las 03:00).';
END;
$$;

COMMIT;