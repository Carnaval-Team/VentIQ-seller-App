-- ============================================================================
-- 03a_compra_esquema.sql — Fase 3: la compra como documento (esquema)
--
-- REQUIERE: 01_motor_dinero.sql y 02a/02b aplicados.
-- Crea 6 tablas, sus restricciones, RLS, el recálculo de totales y el índice
-- de factura por proveedor. Las RPC van en 03b.
--
-- Decisiones que implementa:
--   · `total_mercancia`  = Σ(cantidad × costo_unitario)
--   · `total_ajustes`    = Σ ajustes capitalizados
--   · `total_financiado` = mercancía + ajustes con `origen_pago = 'fondo'`
--   · `costo_aterrizado` = mercancía + TODOS los ajustes (incluido lo que
--                          pagó la wallet de importadora, que capitaliza)
--   · `total_financiado` es inmutable tras reservar (lo impide la fase 4).
--
-- ROLLBACK: 03a_compra_esquema_rollback.sql
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 0) Preflight: sin estas dependencias el script no debe intentar nada
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF to_regclass('public.app_dat_proveedor') IS NULL THEN
        RAISE EXCEPTION 'Falta app_dat_proveedor';
    END IF;
    IF to_regclass('public.app_dat_producto') IS NULL THEN
        RAISE EXCEPTION 'Falta app_dat_producto';
    END IF;
    IF to_regclass('public.app_cont_tipo_costo') IS NULL THEN
        RAISE EXCEPTION 'Falta app_cont_tipo_costo';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema='public' AND table_name='app_dat_proveedor'
                      AND column_name='id') THEN
        RAISE EXCEPTION 'app_dat_proveedor no tiene columna id';
    END IF;
    IF to_regclass('public.fdi_dat_compra') IS NOT NULL THEN
        RAISE EXCEPTION 'fdi_dat_compra ya existe: este script es de creación';
    END IF;
END;
$$;

-- ---------------------------------------------------------------------------
-- 1) Cabecera
-- ---------------------------------------------------------------------------
CREATE TABLE public.fdi_dat_compra (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda          bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    numero_compra      bigint NOT NULL,
    id_proveedor       bigint NOT NULL REFERENCES public.app_dat_proveedor(id),
    numero_factura     text,
    fecha_factura      date,
    moneda_total       text NOT NULL CHECK (moneda_total IN ('USD','CUP','EUR')),
    tasa_factura       numeric(18,10) NOT NULL DEFAULT 1 CHECK (tasa_factura > 0),
    total_mercancia    numeric(14,2) NOT NULL DEFAULT 0,
    total_ajustes      numeric(14,2) NOT NULL DEFAULT 0,
    total_financiado   numeric(14,2) NOT NULL DEFAULT 0,
    costo_aterrizado   numeric(14,2) NOT NULL DEFAULT 0,
    modo_liquidacion   text NOT NULL DEFAULT 'fondo'
                       CHECK (modo_liquidacion IN ('fondo','inversores')),
    politica_pago      text NOT NULL DEFAULT 'al_pagar'
                       CHECK (politica_pago IN ('al_pagar','por_recepcion')),
    estado             text NOT NULL DEFAULT 'creada'
                       CHECK (estado IN ('creada','reservada','pagada','entrega_parcial',
                                         'completada','cancelada','anulada')),
    observacion        text,
    idempotency_key    uuid UNIQUE,
    created_by         uuid,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id_tienda, numero_compra)
);

-- Una factura del mismo proveedor no puede cargarse dos veces.
-- Parcial: las compras sin número de factura (borrador) sí pueden repetirse.
CREATE UNIQUE INDEX idx_fdi_compra_factura
    ON public.fdi_dat_compra (id_tienda, id_proveedor, numero_factura)
    WHERE numero_factura IS NOT NULL AND btrim(numero_factura) <> '';

CREATE INDEX idx_fdi_compra_tienda_estado
    ON public.fdi_dat_compra (id_tienda, estado, fecha_factura DESC);

-- ---------------------------------------------------------------------------
-- 2) Líneas
-- ---------------------------------------------------------------------------
CREATE TABLE public.fdi_dat_compra_linea (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra        bigint NOT NULL REFERENCES public.fdi_dat_compra(id) ON DELETE CASCADE,
    id_tienda        bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_producto      bigint NOT NULL REFERENCES public.app_dat_producto(id),
    id_variante      bigint,
    id_presentacion  bigint,
    cantidad         numeric(14,4) NOT NULL CHECK (cantidad > 0),
    costo_unitario   numeric(14,4) NOT NULL CHECK (costo_unitario >= 0),
    costo_linea      numeric(16,2) GENERATED ALWAYS AS (round(cantidad * costo_unitario, 2)) STORED,
    id_almacen       bigint,
    id_ubicacion     bigint,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_fdi_compra_linea_compra ON public.fdi_dat_compra_linea (id_compra);

-- ---------------------------------------------------------------------------
-- 3) Ajustes de la compra (flete, aduana, servicio de importadora…)
-- ---------------------------------------------------------------------------
CREATE TABLE public.fdi_dat_compra_ajuste (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra           bigint NOT NULL REFERENCES public.fdi_dat_compra(id) ON DELETE CASCADE,
    id_tienda           bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_tipo_costo       bigint REFERENCES public.app_cont_tipo_costo(id),
    base                text NOT NULL DEFAULT 'global'
                        CHECK (base IN ('global','unidad','porcentaje')),
    valor               numeric(14,4) NOT NULL CHECK (valor >= 0),
    reparto             text NOT NULL DEFAULT 'valor'
                        CHECK (reparto IN ('valor','peso','cantidad')),
    monto_capitalizado  numeric(14,2) NOT NULL DEFAULT 0,
    afecta_inventario   boolean NOT NULL DEFAULT true,
    origen_pago         text NOT NULL DEFAULT 'fondo'
                        CHECK (origen_pago IN ('fondo','wallet_importadora',
                                               'wallet_proveedor','externo')),
    estado              text NOT NULL DEFAULT 'declarado'
                        CHECK (estado IN ('declarado','por_financiar','financiado')),
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_fdi_compra_ajuste_compra ON public.fdi_dat_compra_ajuste (id_compra);

-- ---------------------------------------------------------------------------
-- 4) Historial de estados
-- ---------------------------------------------------------------------------
CREATE TABLE public.fdi_hist_estado_compra (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra        bigint NOT NULL REFERENCES public.fdi_dat_compra(id) ON DELETE CASCADE,
    id_tienda        bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    estado_anterior  text,
    estado_nuevo     text NOT NULL,
    origen           text NOT NULL DEFAULT 'manual' CHECK (origen IN ('automatico','manual')),
    motivo           text,
    created_by       uuid,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_fdi_hist_compra ON public.fdi_hist_estado_compra (id_compra, created_at);

-- ---------------------------------------------------------------------------
-- 5) Vínculo compra ↔ recepción (una carga puede cubrir N compras)
-- ---------------------------------------------------------------------------
CREATE TABLE public.fdi_dat_compra_recepcion (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra         bigint NOT NULL REFERENCES public.fdi_dat_compra(id),
    id_tienda         bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_operacion      bigint NOT NULL REFERENCES public.app_dat_operaciones(id),
    monto_valorizado  numeric(14,2) NOT NULL DEFAULT 0,
    moneda            text,
    tasa_a_base       numeric(18,10) NOT NULL DEFAULT 1 CHECK (tasa_a_base > 0),
    created_by        uuid,
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id_operacion, id_compra)
);

CREATE TABLE public.fdi_dat_compra_recepcion_linea (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra_recepcion       bigint NOT NULL
                              REFERENCES public.fdi_dat_compra_recepcion(id) ON DELETE CASCADE,
    id_tienda                 bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_compra_linea           bigint NOT NULL REFERENCES public.fdi_dat_compra_linea(id),
    cantidad_recibida         numeric(14,4) NOT NULL CHECK (cantidad_recibida > 0),
    costo_unitario_aplicado   numeric(14,4),
    id_recepcion_producto     bigint,
    created_at                timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_fdi_compra_rec_linea ON public.fdi_dat_compra_recepcion_linea (id_compra_linea);

-- ---------------------------------------------------------------------------
-- 6) Recálculo de totales
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_fdi_compra_recalcular(p_id_compra bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_merc     numeric;
    v_aj_tot   numeric;
    v_aj_fin   numeric;
BEGIN
    SELECT COALESCE(sum(costo_linea), 0) INTO v_merc
    FROM public.fdi_dat_compra_linea WHERE id_compra = p_id_compra;

    SELECT COALESCE(sum(monto_capitalizado), 0),
           COALESCE(sum(monto_capitalizado) FILTER (WHERE origen_pago = 'fondo'), 0)
      INTO v_aj_tot, v_aj_fin
    FROM public.fdi_dat_compra_ajuste WHERE id_compra = p_id_compra;

    UPDATE public.fdi_dat_compra
       SET total_mercancia  = v_merc,
           total_ajustes    = v_aj_tot,
           total_financiado = v_merc + v_aj_fin,
           costo_aterrizado = v_merc + v_aj_tot,
           updated_at       = now()
     WHERE id = p_id_compra;
END;
$$;

CREATE OR REPLACE FUNCTION public.trg_fdi_compra_recalcular()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM public.fn_fdi_compra_recalcular(COALESCE(NEW.id_compra, OLD.id_compra));
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_fdi_compra_recalc_linea ON public.fdi_dat_compra_linea;
CREATE TRIGGER trg_fdi_compra_recalc_linea
    AFTER INSERT OR UPDATE OR DELETE ON public.fdi_dat_compra_linea
    FOR EACH ROW EXECUTE FUNCTION public.trg_fdi_compra_recalcular();

DROP TRIGGER IF EXISTS trg_fdi_compra_recalc_ajuste ON public.fdi_dat_compra_ajuste;
CREATE TRIGGER trg_fdi_compra_recalc_ajuste
    AFTER INSERT OR UPDATE OR DELETE ON public.fdi_dat_compra_ajuste
    FOR EACH ROW EXECUTE FUNCTION public.trg_fdi_compra_recalcular();

-- ---------------------------------------------------------------------------
-- 7) RLS y permisos: lectura por acceso a la tienda, escritura solo por RPC
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['fdi_dat_compra','fdi_dat_compra_linea','fdi_dat_compra_ajuste',
                             'fdi_hist_estado_compra','fdi_dat_compra_recepcion',
                             'fdi_dat_compra_recepcion_linea']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_select', t);
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (public.fn_user_can_access_tienda(id_tienda))',
            t || '_select', t);
        EXECUTE format('GRANT SELECT ON public.%I TO authenticated', t);
    END LOOP;
END;
$$;

-- Las funciones internas nacen con EXECUTE a PUBLIC: hay que cerrarlas o
-- `anon` puede invocarlas por PostgREST. `fn_fdi_compra_recalcular` es
-- SECURITY DEFINER y escribe totales, así que no debe ser alcanzable.
REVOKE ALL ON FUNCTION public.fn_fdi_compra_recalcular(bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_fdi_compra_recalcular() FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 8) Verificación
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_tablas integer;
    v_rls    integer;
    v_idx    integer;
    v_func   integer;
    v_trig   integer;
BEGIN
    SELECT count(*) INTO v_tablas
    FROM information_schema.tables
    WHERE table_schema='public'
      AND table_name IN ('fdi_dat_compra','fdi_dat_compra_linea','fdi_dat_compra_ajuste',
                         'fdi_hist_estado_compra','fdi_dat_compra_recepcion',
                         'fdi_dat_compra_recepcion_linea');
    IF v_tablas <> 6 THEN
        RAISE EXCEPTION 'Se esperaban 6 tablas y hay %', v_tablas;
    END IF;

    SELECT count(*) INTO v_rls
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname='public' AND c.relrowsecurity
      AND c.relname IN ('fdi_dat_compra','fdi_dat_compra_linea','fdi_dat_compra_ajuste',
                        'fdi_hist_estado_compra','fdi_dat_compra_recepcion',
                        'fdi_dat_compra_recepcion_linea');
    IF v_rls <> 6 THEN
        RAISE EXCEPTION 'RLS activo en % de 6 tablas', v_rls;
    END IF;

    SELECT count(*) INTO v_idx FROM pg_indexes
    WHERE schemaname='public' AND indexname='idx_fdi_compra_factura';
    IF v_idx <> 1 THEN RAISE EXCEPTION 'Falta el índice único de factura'; END IF;

    SELECT count(*) INTO v_func FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname='public' AND p.proname IN ('fn_fdi_compra_recalcular','trg_fdi_compra_recalcular');
    IF v_func <> 2 THEN RAISE EXCEPTION 'Faltan funciones de recálculo'; END IF;

    SELECT count(*) INTO v_trig FROM pg_trigger
    WHERE NOT tgisinternal
      AND tgname IN ('trg_fdi_compra_recalc_linea','trg_fdi_compra_recalc_ajuste');
    IF v_trig <> 2 THEN RAISE EXCEPTION 'Faltan triggers de recálculo'; END IF;
END;
$$;

COMMIT;