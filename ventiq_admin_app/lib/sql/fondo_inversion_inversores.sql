CREATE TABLE IF NOT EXISTS public.fdi_dat_inversor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    nombre text NOT NULL CHECK (length(btrim(nombre)) > 0),
    porcentaje numeric(7,4) NOT NULL CHECK (porcentaje > 0 AND porcentaje <= 100),
    activo boolean NOT NULL DEFAULT true,
    UNIQUE (id, id_tienda)
);
ALTER TABLE public.fdi_dat_inversor ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS fdi_inversor_select ON public.fdi_dat_inversor;
CREATE POLICY fdi_inversor_select ON public.fdi_dat_inversor FOR SELECT TO authenticated
    USING (public.fn_user_is_dueno(id_tienda));
DROP POLICY IF EXISTS fdi_inversor_insert ON public.fdi_dat_inversor;
CREATE POLICY fdi_inversor_insert ON public.fdi_dat_inversor FOR INSERT TO authenticated WITH CHECK (false);
DROP POLICY IF EXISTS fdi_inversor_update ON public.fdi_dat_inversor;
CREATE POLICY fdi_inversor_update ON public.fdi_dat_inversor FOR UPDATE TO authenticated USING (false) WITH CHECK (false);
DROP POLICY IF EXISTS fdi_inversor_delete ON public.fdi_dat_inversor;
CREATE POLICY fdi_inversor_delete ON public.fdi_dat_inversor FOR DELETE TO authenticated USING (false);

CREATE TABLE IF NOT EXISTS public.fdi_dat_inversor_reparto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda bigint NOT NULL REFERENCES public.app_dat_tienda(id),
    id_inversor bigint NOT NULL,
    id_detalle bigint NOT NULL REFERENCES public.fdi_dat_liquidacion_detalle(id),
    nombre_snapshot text NOT NULL,
    porcentaje_snapshot numeric(7,4) NOT NULL,
    moneda text NOT NULL,
    monto numeric NOT NULL CHECK (monto >= 0),
    pagado_at timestamptz,
    pagado_por uuid REFERENCES auth.users(id),
    referencia_pago text,
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (id_inversor, id_tienda) REFERENCES public.fdi_dat_inversor(id, id_tienda),
    UNIQUE (id_detalle, id_inversor),
    CHECK ((pagado_at IS NULL) = (pagado_por IS NULL))
);
ALTER TABLE public.fdi_dat_inversor_reparto ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS fdi_reparto_select ON public.fdi_dat_inversor_reparto;
CREATE POLICY fdi_reparto_select ON public.fdi_dat_inversor_reparto FOR SELECT TO authenticated
    USING (public.fn_user_is_dueno(id_tienda));
DROP POLICY IF EXISTS fdi_reparto_insert ON public.fdi_dat_inversor_reparto;
CREATE POLICY fdi_reparto_insert ON public.fdi_dat_inversor_reparto FOR INSERT TO authenticated WITH CHECK (false);
DROP POLICY IF EXISTS fdi_reparto_update ON public.fdi_dat_inversor_reparto;
CREATE POLICY fdi_reparto_update ON public.fdi_dat_inversor_reparto FOR UPDATE TO authenticated USING (false) WITH CHECK (false);
DROP POLICY IF EXISTS fdi_reparto_delete ON public.fdi_dat_inversor_reparto;
CREATE POLICY fdi_reparto_delete ON public.fdi_dat_inversor_reparto FOR DELETE TO authenticated USING (false);

CREATE OR REPLACE FUNCTION public.fn_fdi_validar_monto_reparto() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    IF NEW.monto <> trunc(NEW.monto) THEN
        RAISE EXCEPTION 'El importe del inversor debe ser entero';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_fdi_validar_monto_reparto ON public.fdi_dat_inversor_reparto;
CREATE TRIGGER trg_fdi_validar_monto_reparto
BEFORE INSERT OR UPDATE OF monto ON public.fdi_dat_inversor_reparto
FOR EACH ROW EXECUTE FUNCTION public.fn_fdi_validar_monto_reparto();
REVOKE ALL ON FUNCTION public.fn_fdi_validar_monto_reparto() FROM PUBLIC;

CREATE INDEX IF NOT EXISTS fdi_reparto_tienda_inversor ON public.fdi_dat_inversor_reparto(id_tienda, id_inversor, created_at);
GRANT SELECT ON public.fdi_dat_inversor, public.fdi_dat_inversor_reparto TO authenticated;

CREATE OR REPLACE FUNCTION public.fn_fdi_guardar_inversor(p_id_tienda bigint, p_nombre text, p_porcentaje numeric, p_activo boolean, p_id bigint DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id bigint;
BEGIN
    IF NOT COALESCE(public.fn_user_is_dueno(p_id_tienda), false) THEN
        RAISE EXCEPTION 'Solo el dueño puede gestionar inversores' USING ERRCODE = '42501';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('fdi_inversores:' || p_id_tienda, 0));
    IF p_id IS NULL THEN
        INSERT INTO public.fdi_dat_inversor(id_tienda, nombre, porcentaje, activo)
        VALUES (p_id_tienda, btrim(p_nombre), p_porcentaje, p_activo) RETURNING id INTO v_id;
    ELSE
        UPDATE public.fdi_dat_inversor SET nombre = btrim(p_nombre), porcentaje = p_porcentaje, activo = p_activo
        WHERE id = p_id AND id_tienda = p_id_tienda RETURNING id INTO v_id;
        IF v_id IS NULL THEN RAISE EXCEPTION 'Inversor no encontrado'; END IF;
    END IF;
    RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_repartir_ganancia() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_tienda bigint;
    v_igual  boolean;
    v_total  numeric;
    v_n      integer;
    v_monto  numeric;
    v_pct    numeric;
    v_i record;
BEGIN
    SELECT id_tienda, repartir_igual INTO STRICT v_tienda, v_igual
    FROM public.fdi_dat_liquidacion WHERE id = NEW.id_liquidacion;
    IF NOT COALESCE(public.fn_user_is_dueno(v_tienda), false) THEN
        RAISE EXCEPTION 'Solo el dueño puede liquidar ganancias' USING ERRCODE = '42501';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('fdi_inversores:' || v_tienda, 0));
    SELECT sum(porcentaje), count(*) INTO v_total, v_n
    FROM public.fdi_dat_inversor WHERE id_tienda = v_tienda AND activo;
    IF v_n IS NULL OR v_n = 0 THEN
        RAISE EXCEPTION 'No hay inversores activos para repartir la ganancia';
    END IF;
    IF NOT v_igual AND v_total IS DISTINCT FROM 100::numeric THEN
        RAISE EXCEPTION 'La participación de los inversores activos debe sumar 100%%';
    END IF;
    IF NEW.monto_ganancia_retirada = 0 THEN RETURN NEW; END IF;
    IF NEW.monto_ganancia_retirada <> round(NEW.monto_ganancia_retirada, 2) THEN
        RAISE EXCEPTION 'La ganancia retirada debe tener como máximo dos decimales';
    END IF;
    FOR v_i IN SELECT * FROM public.fdi_dat_inversor WHERE id_tienda = v_tienda AND activo ORDER BY id LOOP
        v_pct := CASE WHEN v_igual THEN 100.0 / v_n ELSE v_i.porcentaje END;
        -- En ambos modos nadie absorbe el remanente: los importes enteros
        -- se asignan a inversores y la diferencia queda en el fondo.
        v_monto := CASE WHEN v_igual THEN trunc(NEW.monto_ganancia_retirada / v_n)
                        ELSE trunc(NEW.monto_ganancia_retirada * v_i.porcentaje / 100) END;
        INSERT INTO public.fdi_dat_inversor_reparto(id_tienda, id_inversor, id_detalle, nombre_snapshot, porcentaje_snapshot, moneda, monto)
        VALUES (v_tienda, v_i.id, NEW.id, v_i.nombre, v_pct, NEW.moneda, v_monto);
    END LOOP;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_fdi_repartir_ganancia ON public.fdi_dat_liquidacion_detalle;
CREATE TRIGGER trg_fdi_repartir_ganancia AFTER INSERT ON public.fdi_dat_liquidacion_detalle
FOR EACH ROW EXECUTE FUNCTION public.fn_fdi_repartir_ganancia();

CREATE OR REPLACE FUNCTION public.fn_fdi_pagar_inversor(p_id_reparto bigint, p_referencia text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_r public.fdi_dat_inversor_reparto%ROWTYPE;
BEGIN
    SELECT * INTO STRICT v_r FROM public.fdi_dat_inversor_reparto WHERE id = p_id_reparto FOR UPDATE;
    IF NOT COALESCE(public.fn_user_is_dueno(v_r.id_tienda), false) THEN
        RAISE EXCEPTION 'Solo el dueño puede confirmar pagos' USING ERRCODE = '42501';
    END IF;
    IF v_r.pagado_at IS NOT NULL THEN RETURN; END IF;
    IF p_referencia IS NULL OR btrim(p_referencia) = '' THEN RAISE EXCEPTION 'Indique la referencia del pago'; END IF;
    IF v_r.monto <= 0 THEN RAISE EXCEPTION 'El reparto no tiene monto pendiente'; END IF;
    UPDATE public.fdi_dat_inversor_reparto SET pagado_at = now(), pagado_por = auth.uid(), referencia_pago = btrim(p_referencia)
    WHERE id = p_id_reparto;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_fdi_historial_inversores(p_id_tienda bigint, p_desde date DEFAULT NULL, p_hasta date DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF NOT COALESCE(public.fn_user_is_dueno(p_id_tienda), false) THEN
        RAISE EXCEPTION 'Solo el dueño puede consultar repartos' USING ERRCODE = '42501';
    END IF;
    IF p_desde > p_hasta THEN RAISE EXCEPTION 'Periodo inválido'; END IF;
    RETURN COALESCE((SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id DESC) FROM (
        SELECT r.*, d.id_liquidacion, d.id_medio_pago, l.fecha_desde, l.fecha_hasta
        FROM public.fdi_dat_inversor_reparto r
        JOIN public.fdi_dat_liquidacion_detalle d ON d.id = r.id_detalle
        JOIN public.fdi_dat_liquidacion l ON l.id = d.id_liquidacion
        WHERE r.id_tienda = p_id_tienda
          AND (p_desde IS NULL OR l.fecha_hasta >= p_desde)
          AND (p_hasta IS NULL OR l.fecha_desde <= p_hasta)
    ) x), '[]'::jsonb);
END;
$$;

REVOKE ALL ON FUNCTION public.fn_fdi_guardar_inversor(bigint,text,numeric,boolean,bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_fdi_pagar_inversor(bigint,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_fdi_historial_inversores(bigint,date,date) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_fdi_repartir_ganancia() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_fdi_guardar_inversor(bigint,text,numeric,boolean,bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_fdi_pagar_inversor(bigint,text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_fdi_historial_inversores(bigint,date,date) TO authenticated;

COMMIT;
