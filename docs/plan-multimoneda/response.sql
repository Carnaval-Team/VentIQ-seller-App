CREATE OR REPLACE FUNCTION carnavalapp.fn_log_carrito_eliminacion()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'carnavalapp', 'public', 'pg_temp'
AS $function$DECLARE
  v_motivo           text := COALESCE(NULLIF(current_setting('carnavalapp.delete_motivo', true), ''), 'manual');
  v_veces            integer;
  v_count_ventana    integer;
  v_limite  constant integer  := 5;
  v_ventana constant interval := interval '2 hours';
  v_temporal constant interval := interval '24 hours';
  v_bloqueo          carnavalapp.carrito_bloqueos%ROWTYPE;
  v_producto_nombre  text;
  v_nuevo_tipo       text := NULL;
  v_fecha_fin        timestamptz;
  v_soporte          text;
  v_contacto_txt     text;
  v_constraint_name  text;
BEGIN
  -- No aplicar historial/antiabuso a filas huérfanas de usuario.
  IF NOT EXISTS (
    SELECT 1
      FROM carnavalapp."Usuarios" u
     WHERE u.id = OLD.user_id
  ) THEN
    RETURN OLD;
  END IF;

  SELECT COUNT(*) + 1 INTO v_veces
    FROM carnavalapp.carrito_historial_eliminaciones h
   WHERE h.user_id = OLD.user_id
     AND h.id_producto = OLD.product_id
     AND h.motivo <> 'orden';

  -- Protege también contra la eliminación concurrente del usuario.
  BEGIN
    INSERT INTO carnavalapp.carrito_historial_eliminaciones
      (user_id, id_producto, uuid, cantidad_eliminada, motivo, cantidad_veces_elimino_el_producto)
    VALUES
      (OLD.user_id, OLD.product_id, OLD.uuid, OLD.quantity, v_motivo,
       CASE WHEN v_motivo = 'orden' THEN 0 ELSE v_veces END);
  EXCEPTION WHEN foreign_key_violation THEN
    GET STACKED DIAGNOSTICS v_constraint_name = CONSTRAINT_NAME;
    IF v_constraint_name = 'fk_hist_elim_usuario' THEN
      RETURN OLD;
    END IF;
    RAISE;
  END;

  IF v_motivo = 'orden' THEN
    RETURN OLD;
  END IF;

  SELECT COUNT(*) INTO v_count_ventana
    FROM carnavalapp.carrito_historial_eliminaciones h
   WHERE h.user_id = OLD.user_id
     AND h.id_producto = OLD.product_id
     AND h.motivo <> 'orden'
     AND h.fecha_eliminacion > now() - v_ventana;

  IF v_count_ventana < v_limite THEN
    RETURN OLD;
  END IF;

  SELECT * INTO v_bloqueo
    FROM carnavalapp.carrito_bloqueos b
   WHERE b.user_id = OLD.user_id
     AND b.id_producto = OLD.product_id;

  IF NOT FOUND THEN
    v_nuevo_tipo := 'temporal';
    v_fecha_fin  := now() + v_temporal;
    INSERT INTO carnavalapp.carrito_bloqueos
      (user_id, id_producto, uuid, tipo, fecha_inicio, fecha_fin, veces_bloqueado, motivo, updated_at)
    VALUES
      (OLD.user_id, OLD.product_id, OLD.uuid, 'temporal', now(), v_fecha_fin, 1,
       'Eliminacion repetida del producto en menos de 2 horas', now());
  ELSIF v_bloqueo.tipo = 'permanente' THEN
    RETURN OLD;
  ELSIF v_bloqueo.fecha_fin IS NOT NULL AND v_bloqueo.fecha_fin > now() THEN
    RETURN OLD;
  ELSE
    v_nuevo_tipo := 'permanente';
    v_fecha_fin  := NULL;
    UPDATE carnavalapp.carrito_bloqueos b
       SET tipo = 'permanente',
           fecha_inicio = now(),
           fecha_fin = NULL,
           veces_bloqueado = b.veces_bloqueado + 1,
           motivo = 'Reincidencia: repitio el patron tras un bloqueo temporal',
           updated_at = now()
     WHERE b.user_id = OLD.user_id
       AND b.id_producto = OLD.product_id;
  END IF;

  SELECT p.name INTO v_producto_nombre
    FROM carnavalapp."Productos" p
   WHERE p.id = OLD.product_id;

  SELECT COALESCE(NULLIF(c.numero_contacto::text, ''), NULLIF(c.numero_soporte_tecnico::text, ''))
    INTO v_soporte
    FROM carnavalapp.configuraciones_admin c
   ORDER BY c.id
   LIMIT 1;

  v_contacto_txt := CASE
    WHEN v_soporte IS NOT NULL THEN
      ' Si crees que se trata de un error, contacta con soporte al numero ' || v_soporte ||
      ' para revisar tu caso y, de ser procedente, desbloquear el producto.'
    ELSE
      ' Si crees que se trata de un error, contacta con soporte para revisar tu caso y, de ser procedente, desbloquear el producto.'
  END;

  INSERT INTO carnavalapp.notificaciones_usuario
    (titulo, descripcion, id_usuario, tipo, referencia_id, leida)
  VALUES (
    CASE WHEN v_nuevo_tipo = 'permanente'
         THEN 'Producto bloqueado permanentemente'
         ELSE 'Producto bloqueado temporalmente' END,
    (CASE WHEN v_nuevo_tipo = 'permanente'
         THEN 'Has vuelto a eliminar repetidamente el producto "' || COALESCE(v_producto_nombre, '#' || OLD.product_id) ||
              '" del carrito. Por reincidencia en un patron que se detecta como intento de reservar productos de forma indebida o de vulnerar la aplicacion, este producto ha quedado bloqueado de forma permanente para tu cuenta.'
         ELSE 'Detectamos que eliminaste el producto "' || COALESCE(v_producto_nombre, '#' || OLD.product_id) ||
              '" del carrito varias veces en menos de 2 horas. Por seguridad no podras volver a agregarlo durante 24 horas. Este patron se detecta como un intento de reservar productos de forma indebida o de vulnerar la aplicacion.'
     END) || v_contacto_txt,
    OLD.uuid::text,
    'error',
    OLD.product_id,
    false
  );

  RETURN OLD;
END;$function$;


CREATE OR REPLACE FUNCTION public.fn_app_version_eliminar(p_id integer)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_row    public.app_versiones%rowtype;
  v_ultima boolean := false;
  v_data   jsonb;
begin
  if not public.fn_is_superadmin_full_access() then
    return json_build_object('ok', false, 'error', 'Solo el superadmin puede gestionar versiones');
  end if;

  if p_id is null then
    return json_build_object('ok', false, 'error', 'Falta el id de la version');
