CREATE OR REPLACE FUNCTION carnavalapp.fn_check_carrito_abuse()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'carnavalapp', 'public', 'pg_temp'
AS $function$
DECLARE
  v_bloqueo carnavalapp.carrito_bloqueos%ROWTYPE;
BEGIN
  SELECT * INTO v_bloqueo
    FROM carnavalapp.carrito_bloqueos b
   WHERE b.user_id = NEW.user_id
     AND b.id_producto = NEW.product_id;

  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  IF v_bloqueo.tipo = 'permanente' THEN
    RAISE EXCEPTION
      'Este producto esta bloqueado de forma PERMANENTE para tu cuenta por reincidir en un patron de eliminaciones repetidas, detectado como intento de reservar productos de forma indebida o de vulnerar la aplicacion.'
      USING ERRCODE = 'check_violation',
            HINT = 'Contacta con soporte si crees que es un error.';
  ELSIF v_bloqueo.fecha_fin IS NOT NULL AND v_bloqueo.fecha_fin > now() THEN
    RAISE EXCEPTION
      'Este producto esta bloqueado temporalmente para tu cuenta hasta % por eliminarlo repetidamente en poco tiempo. Este patron se detecta como intento de reservar productos de forma indebida o de vulnerar la aplicacion.',
      to_char(v_bloqueo.fecha_fin AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI') || ' UTC'
      USING ERRCODE = 'check_violation',
            HINT = 'Espera a que termine el bloqueo temporal antes de volver a agregarlo.';
  END IF;

  -- Bloqueo temporal expirado: se permite (la reincidencia se evaluara en el
  -- AFTER DELETE si vuelve a repetir el patron).
  RETURN NEW;
END;
$function$;


CREATE OR REPLACE FUNCTION carnavalapp.fn_desbloquear_carrito(p_user_id bigint, p_id_producto bigint, p_limpiar_historial boolean DEFAULT true)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'carnavalapp', 'public', 'pg_temp'
AS $function$
DECLARE
  v_uuid            uuid;
  v_producto_nombre text;
  v_borrados_bloqueo integer := 0;
  v_borrados_hist    integer := 0;
BEGIN
  IF p_user_id IS NULL OR p_id_producto IS NULL THEN
    RAISE EXCEPTION 'p_user_id y p_id_producto son obligatorios';
  END IF;

  SELECT b.uuid INTO v_uuid
    FROM carnavalapp.carrito_bloqueos b
   WHERE b.user_id = p_user_id AND b.id_producto = p_id_producto;

  DELETE FROM carnavalapp.carrito_bloqueos b
   WHERE b.user_id = p_user_id AND b.id_producto = p_id_producto;
  GET DIAGNOSTICS v_borrados_bloqueo = ROW_COUNT;

  IF COALESCE(p_limpiar_historial, true) THEN
    -- Solo elimina las eliminaciones manuales recientes (ventana de 2h) para
    -- resetear el patron sin borrar el historial de auditoria antiguo.
    DELETE FROM carnavalapp.carrito_historial_eliminaciones h
     WHERE h.user_id = p_user_id
       AND h.id_producto = p_id_producto
       AND h.motivo <> 'orden'
       AND h.fecha_eliminacion > now() - interval '2 hours';
    GET DIAGNOSTICS v_borrados_hist = ROW_COUNT;
  END IF;

  IF v_uuid IS NULL THEN
    SELECT u.uuid INTO v_uuid FROM carnavalapp."Usuarios" u WHERE u.id = p_user_id;
  END IF;

  SELECT p.name INTO v_producto_nombre FROM carnavalapp."Productos" p WHERE p.id = p_id_producto;

  IF v_borrados_bloqueo > 0 AND v_uuid IS NOT NULL THEN
    INSERT INTO carnavalapp.notificaciones_usuario
      (titulo, descripcion, id_usuario, tipo, referencia_id, leida)
    VALUES (
      'Producto desbloqueado',
      'Hemos revisado tu caso y desbloqueado el producto "' ||
        COALESCE(v_producto_nombre, '#' || p_id_producto) ||
        '". Ya puedes volver a agregarlo al carrito. Gracias por tu comprension.',
      v_uuid::text,
      'success',
      p_id_producto,
      false
    );
  END IF;

  RETURN jsonb_build_object(
    'desbloqueado',       v_borrados_bloqueo > 0,
    'bloqueos_eliminados', v_borrados_bloqueo,
    'historial_limpiado',  v_borrados_hist,
    'user_id',            p_user_id,
    'id_producto',        p_id_producto
  );
END;
$function$;
