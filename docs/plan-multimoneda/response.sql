CREATE OR REPLACE FUNCTION public.fn_cerrar_precios_venta_activos_duplicados(p_tienda_id bigint DEFAULT NULL::bigint, p_producto_id bigint DEFAULT NULL::bigint, p_dry_run boolean DEFAULT true)
 RETURNS TABLE(id_precio bigint, id_producto bigint, id_variante bigint, precio_venta_cup numeric, fecha_desde date, fecha_hasta_anterior date, fecha_hasta_nueva date, id_keeper bigint, accion text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_updated INT := 0;
BEGIN
    RETURN QUERY
    WITH ranked AS (
        SELECT
            pv.id,
            pv.id_producto,
            pv.id_variante,
            COALESCE(pv.id_variante, 0) AS id_variante_key,
            pv.precio_venta_cup,
            pv.fecha_desde,
            pv.fecha_hasta,
            ROW_NUMBER() OVER (
                PARTITION BY pv.id_producto, COALESCE(pv.id_variante, 0)
                ORDER BY pv.fecha_desde DESC NULLS LAST, pv.id DESC
            ) AS rn
        FROM public.app_dat_precio_venta pv
        JOIN public.app_dat_producto p ON p.id = pv.id_producto
        WHERE (pv.fecha_hasta IS NULL OR pv.fecha_hasta >= CURRENT_DATE)
          AND (p_producto_id IS NULL OR pv.id_producto = p_producto_id)
          AND (p_tienda_id   IS NULL OR p.id_tienda   = p_tienda_id)
    ),
    keepers AS (
        SELECT r.*
        FROM ranked r
        WHERE r.rn = 1
    ),
    to_close AS (
        SELECT
            r.id,
            r.id_producto,
            r.id_variante,
            r.precio_venta_cup,
            r.fecha_desde,
            r.fecha_hasta,
            k.id AS id_keeper,
            (k.fecha_desde - INTERVAL '1 day')::DATE AS fecha_hasta_calc
        FROM ranked r
        JOIN keepers k
          ON k.id_producto = r.id_producto
         AND k.id_variante_key = r.id_variante_key
        WHERE r.rn > 1
    ),
    updated AS (
        UPDATE public.app_dat_precio_venta pv
        SET fecha_hasta = tc.fecha_hasta_calc
        FROM to_close tc
        WHERE pv.id = tc.id
          AND p_dry_run = FALSE
          AND (pv.fecha_hasta IS DISTINCT FROM tc.fecha_hasta_calc)
        RETURNING
            pv.id,
            pv.id_producto,
            pv.id_variante,
            pv.precio_venta_cup,
            pv.fecha_desde,
            tc.fecha_hasta AS fecha_hasta_anterior,
            pv.fecha_hasta AS fecha_hasta_nueva,
            tc.id_keeper
    )
    SELECT
        tc.id,
        tc.id_producto,
        tc.id_variante,
        tc.precio_venta_cup,
        tc.fecha_desde,
        tc.fecha_hasta,
        tc.fecha_hasta_calc,
        tc.id_keeper,
        CASE
            WHEN p_dry_run THEN 'DRY_RUN_CERRARIA'::TEXT
            ELSE 'CERRADO'::TEXT
        END
    FROM to_close tc
    WHERE p_dry_run = TRUE

    UNION ALL

    SELECT
        u.id,
        u.id_producto,
        u.id_variante,
        u.precio_venta_cup,
        u.fecha_desde,
        u.fecha_hasta_anterior,
        u.fecha_hasta_nueva,
        u.id_keeper,
        'CERRADO'::TEXT
    FROM updated u
    WHERE p_dry_run = FALSE

    ORDER BY 2, 3 NULLS FIRST, 1;

    IF NOT p_dry_run THEN
        GET DIAGNOSTICS v_updated = ROW_COUNT;
        RAISE NOTICE 'fn_cerrar_precios_venta_activos_duplicados: filas cerradas=%', v_updated;
    END IF;
END;
$function$;
