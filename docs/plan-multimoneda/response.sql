    v_data := v_data || jsonb_build_object('aviso',
      'Era la ultima version activa de ' || v_row.app_name ||
      ': esa app dejara de avisar de actualizaciones hasta que publiques otra.');
  end if;

  return json_build_object('ok', true, 'data', v_data);
